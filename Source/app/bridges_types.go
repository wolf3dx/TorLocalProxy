package main

// Отдельное поле на каждый тип мостов.
//
// Сначала все мосты жили в одном поле. Это было упрощением, и оно
// мешало: типов стало четыре, набор каждого добывается отдельно, и
// увидеть в общей простыне, сколько чего лежит и что править, нельзя.
// Теперь у каждого типа своё поле.
//
// Почему выбор типа сделан списком, а не вкладками. Вкладки я сначала и
// поставил — и они не влезли: пять названий с отметками занимают больше
// ширины, чем есть у телефона, пятая вкладка уезжала за край вместе с
// подписью соседней кнопки. Список занимает одну строку при любом числе
// типов и показывает в ней же, сколько мостов на выбранном.
//
// Хранится всё по-прежнему одним файлом — поля собираются из него при
// открытии и складываются обратно при сохранении. Так и старые
// сохранения читаются, и ядру ничего не пришлось знать про интерфейс.
//
// Главное свойство: строки сами попадают в поле своего типа. Можно
// вставить письмо от BridgeDB целиком в любое поле и нажать
// «Разложить» — мосты разойдутся по типам, а приветствие и подпись
// отбросятся.

import (
	"fmt"
	"strings"

	"fyne.io/fyne/v2"
	"fyne.io/fyne/v2/container"
	"fyne.io/fyne/v2/widget"

	"gitlab.com/vkandreevich/torlocalproxy/core/bridges"
)

// ТипПрочие — куда попадают мосты без транспорта и незнакомых типов.
const ТипПрочие = "прочие"

// типыМостов — порядок типов. Тот же, в котором приложение перебирает
// их при подключении: первым идёт то, что пробуется раньше.
var типыМостов = []string{"webtunnel", "obfs4", "snowflake", "meek_lite", ТипПрочие}

// собратьПоляМостов создаёт по полю на тип и переключатель между ними.
func (э *экран) собратьПоляМостов() fyne.CanvasObject {
	э.поля = make(map[string]*widget.Entry, len(типыМостов))

	// Все поля лежат в одной стопке, видно только выбранное. Так правки
	// не теряются при переключении: поле не пересоздаётся и текст в нём
	// остаётся своим.
	слои := make([]fyne.CanvasObject, 0, len(типыМостов))
	for _, тип := range типыМостов {
		поле := widget.NewMultiLineEntry()
		поле.SetMinRowsVisible(4)
		// Перенос обязателен: строки мостов длинные, и без него поле
		// растягивает всю плашку шире экрана телефона.
		поле.Wrapping = fyne.TextWrapBreak
		поле.SetPlaceHolder(подсказкаТипа(тип))
		поле.Hide()

		э.поля[тип] = поле
		слои = append(слои, поле)
	}
	э.стопкаПолей = container.NewStack(слои...)

	э.выборТипа = widget.NewSelect(нетПодписей(), func(выбранное string) {
		э.показатьТип(типИзПодписи(выбранное))
	})

	э.показатьТип(типыМостов[0])
	return container.NewVBox(э.выборТипа, э.стопкаПолей)
}

// показатьТип оставляет на виду поле одного типа.
func (э *экран) показатьТип(тип string) {
	if _, есть := э.поля[тип]; !есть {
		тип = типыМостов[0]
	}
	э.текущийТип = тип
	for имя, поле := range э.поля {
		if имя == тип {
			поле.Show()
		} else {
			поле.Hide()
		}
	}
	э.стопкаПолей.Refresh()
}

// нетПодписей — начальные подписи списка, до подсчёта мостов.
func нетПодписей() []string {
	подписи := make([]string, 0, len(типыМостов))
	for _, тип := range типыМостов {
		подписи = append(подписи, тип)
	}
	return подписи
}

// типИзПодписи достаёт имя типа из подписи вида «obfs4 — 4 моста».
func типИзПодписи(подпись string) string {
	if место := strings.Index(подпись, " "); место > 0 {
		return подпись[:место]
	}
	return подпись
}

// подсказкаТипа — что написано в пустом поле. Не украшение: у каждого
// типа свой способ получить мосты, и человек должен видеть, куда идти.
func подсказкаТипа(тип string) string {
	switch тип {
	case "webtunnel":
		return "Мосты webtunnel: запросить у @GetBridgesBot\n" +
			"или письмом на bridges@torproject.org\n" +
			"с текстом: get transport webtunnel"
	case "obfs4":
		return "Мосты obfs4: там же, где webtunnel.\n" +
			"На мобильных сетях их часто глушат —\n" +
			"держите про запас другой тип."
	case "snowflake":
		return "Заказывать не нужно: нажмите «Встроенные».\n" +
			"Строка одна для всех, идёт к добровольцам."
	case "meek_lite":
		return "Заказывать не нужно: нажмите «Встроенные».\n" +
			"Самый медленный и самый живучий."
	default:
		return "Мосты без транспорта и незнакомых типов.\n" +
			"Обычно это поле остаётся пустым."
	}
}

// текстМостов собирает содержимое всех вкладок в один текст — тот, что
// уходит на сохранение и в подключение.
func (э *экран) текстМостов() string {
	части := make([]string, 0, len(типыМостов))
	for _, тип := range типыМостов {
		текст := strings.TrimSpace(э.поля[тип].Text)
		if текст != "" {
			части = append(части, текст)
		}
	}
	return strings.Join(части, "\n")
}

// разложитьПоТипам раскладывает любой текст с мостами по полям типов.
//
// Возвращает, сколько мостов разобрано и сколько строк отброшено как
// посторонние. Отброшенные — это приветствие и подпись из письма: в
// полях они не нужны, а раньше только мешали читать.
func (э *экран) разложитьПоТипам(текст string) (разобрано, отброшено int) {
	по := make(map[string][]string, len(типыМостов))
	уже := make(map[string]bool)

	for _, строка := range strings.Split(текст, "\n") {
		обрезанная := strings.TrimSpace(строка)
		if обрезанная == "" {
			continue
		}
		мост, err := bridges.ParseLine(обрезанная)
		if err != nil {
			отброшено++
			continue
		}
		// Повторы приходят сами: письма присылают дважды, файлы
		// дописывают. Подпись «мостов: 8» при четырёх настоящих —
		// прямой обман, поэтому дубликаты отбрасываем.
		if уже[мост.Short()] {
			continue
		}
		уже[мост.Short()] = true

		тип := мост.Transport
		if _, свой := э.поля[тип]; !свой {
			тип = ТипПрочие
		}
		по[тип] = append(по[тип], обрезанная)
		разобрано++
	}

	for _, тип := range типыМостов {
		э.поля[тип].SetText(strings.Join(по[тип], "\n"))
	}
	э.обновитьПодписи()
	return разобрано, отброшено
}

// обновитьПодписи пересчитывает мосты и обновляет и список типов, и
// подпись плашки.
//
// Ради этих чисел отдельные поля и заводились: видно, где мосты есть, а
// где пусто, не переключаясь между типами.
func (э *экран) обновитьПодписи() {
	подписи := make([]string, 0, len(типыМостов))
	всего := 0
	текущая := ""

	for _, тип := range типыМостов {
		годные, _ := bridges.Parse(э.поля[тип].Text)
		подпись := тип
		if len(годные) > 0 {
			подпись = fmt.Sprintf("%s — %d", тип, len(годные))
			всего += len(годные)
		} else {
			подпись = тип + " — пусто"
		}
		подписи = append(подписи, подпись)
		if тип == э.текущийТип {
			текущая = подпись
		}
	}

	// Список пересобирается целиком: у Select нет способа переписать
	// одну строку, а сохранять выбор надо — иначе поле на глазах
	// перескакивает на другой тип.
	э.выборТипа.Options = подписи
	э.выборТипа.Selected = текущая
	э.выборТипа.Refresh()

	if всего == 0 {
		э.плашкаМостов.SetSubTitle("пусто — подключение напрямую")
		return
	}
	// Подпись держится короткой сознательно: числа по типам уже стоят в
	// списке выше, а длинная подпись растягивает плашку шире экрана —
	// на этом я попался, когда перечислял в ней все четыре типа.
	э.плашкаМостов.SetSubTitle(fmt.Sprintf(
		"мостов: %d, типы пробуются по порядку списка", всего))
}
