package main

import (
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
)

// Настройки — это выбранная тема и галочки. Потерять их не страшно, но
// обидно, а молча потерять при переезде из профиля — обиднее всего.

// чистыеНастройки даёт тесту пустое хранилище во временном каталоге и
// отрезает перенос из профиля: иначе тест читал бы настоящие настройки
// того, кто запустил сборку.
func чистыеНастройки(t *testing.T) string {
	t.Helper()
	прежний := источникПереноса
	источникПереноса = func() string { return "" }
	t.Cleanup(func() { источникПереноса = прежний })

	корень := t.TempDir()
	открытьНастройки(корень)
	return корень
}

func TestНастройкиПереживаютПерезапуск(t *testing.T) {
	корень := чистыеНастройки(t)

	записатьНастройку(ключТемы, "clay")
	записатьНастройку(ключАвтоподключения, true)

	// «Перезапуск»: забываем всё и читаем файл заново.
	настройки.значения = map[string]any{}
	открытьНастройки(корень)

	if получено := настройкаСтрока(ключТемы, "night"); получено != "clay" {
		t.Errorf("тема после перезапуска = %q, хотим %q", получено, "clay")
	}
	if !настройкаФлаг(ключАвтоподключения) {
		t.Error("галочка автоподключения после перезапуска потерялась")
	}
}

func TestПустыеНастройкиДаютЗапасное(t *testing.T) {
	чистыеНастройки(t)

	if получено := настройкаСтрока(ключТемы, "night"); получено != "night" {
		t.Errorf("тема по умолчанию = %q, хотим %q", получено, "night")
	}
	if настройкаФлаг(ключАвтоподключения) {
		t.Error("автоподключение по умолчанию должно быть выключено")
	}
}

// Битый файл не должен ронять приложение: лучше запуститься с
// настройками по умолчанию, чем не запуститься вовсе.
func TestБитыйФайлНеРонит(t *testing.T) {
	корень := чистыеНастройки(t)
	if err := os.WriteFile(filepath.Join(корень, ИмяФайлаНастроек),
		[]byte("{это не json"), 0o600); err != nil {
		t.Fatal(err)
	}

	открытьНастройки(корень)

	if получено := настройкаСтрока(ключТемы, "night"); получено != "night" {
		t.Errorf("из битого файла взялось %q вместо запасного", получено)
	}
}

// Формат файла — тот же плоский JSON, что у Fyne. Это не прихоть: так
// настройки из прежнего места читаются без перевода.
func TestФорматФайлаПлоскийJSON(t *testing.T) {
	корень := чистыеНастройки(t)
	записатьНастройку(ключТемы, "day")

	данные, err := os.ReadFile(filepath.Join(корень, ИмяФайлаНастроек))
	if err != nil {
		t.Fatal(err)
	}
	var разобрано map[string]any
	if err := json.Unmarshal(данные, &разобрано); err != nil {
		t.Fatalf("файл настроек не разбирается как JSON: %v", err)
	}
	if разобрано[ключТемы] != "day" {
		t.Errorf("в файле %v, хотим day", разобрано[ключТемы])
	}
}
