// Галочка «подключаться сразу» ценна не сама по себе, а тем, что её
// выбор переживает закрытие приложения. Проверяем именно это: нажали —
// в настройках записалось; прочитали — приложение узнаёт о выборе.

func TestГалочкаАвтоподключенияПишетНастройку(t *testing.T) {
	приложение := test.NewApp()
	defer test.NewApp() // вернуть окружение следующим тестам
	окно := test.NewWindow(nil)
	defer окно.Close()

	э := &экран{}
	содержимое := э.собратьЭкранНастроек(окно, приложение)

	галочка := найтиГалочку(содержимое, "Подключаться сразу при запуске")
	if галочка == nil {
		t.Fatal("на экране настроек нет галочки автоподключения")
	}
	if галочка.Checked {
		t.Error("по умолчанию автоподключение должно быть выключено")
	}

	галочка.SetChecked(true)
	if !автоподключениеВключено(приложение) {
		t.Error("галочку поставили, а настройка не записалась")
	}

	галочка.SetChecked(false)
	if автоподключениеВключено(приложение) {
		t.Error("галочку сняли, а настройка осталась")
	}
}

// На компьютере настройка автозапуска должна быть на экране: ради неё
// экран и заводили.
func TestНаКомпьютереЕстьГалочкаАвтозапуска(t *testing.T) {
	if !автозапускДоступен() {
		t.Skip("система автозапуск не поддерживает")
	}
	приложение := test.NewApp()
	defer test.NewApp()
	окно := test.NewWindow(nil)
	defer окно.Close()

	э := &экран{}
	if найтиГалочку(э.собратьЭкранНастроек(окно, приложение),
		"Запускать при входе в систему") == nil {
		t.Error("на экране настроек нет галочки автозапуска")
	}
}

// найтиГалочку обходит дерево виджетов и возвращает галочку с такой
// подписью. Экран собирается из вложенных контейнеров, и добираться до
// неё по индексам значило бы ломать тест при каждой перестановке.
func найтиГалочку(объект fyne.CanvasObject, подпись string) *widget.Check {
	switch о := объект.(type) {
	case *widget.Check:
		if о.Text == подпись {
			return о
		}
	case *fyne.Container:
		for _, вложенный := range о.Objects {
			if найдено := найтиГалочку(вложенный, подпись); найдено != nil {
				return найдено
			}
		}
	case *widget.Card:
		return найтиГалочку(о.Content, подпись)
	case fyne.Widget:
		// Прокрутка и прочие обёртки прячут содержимое в своём
		// отрисовщике — туда и смотрим.
		for _, вложенный := range test.WidgetRenderer(о).Objects() {
			if найдено := найтиГалочку(вложенный, подпись); найдено != nil {
				return найдено
			}
		}
	}
	return nil
}
