// настроитьПлатформу на iPhone ничего не делает: окно там не закрывают
// крестиком, а за живучесть отвечает удержатьВФоне.
func настроитьПлатформу(fyne.App, fyne.Window, *service.Service) {}

// удержатьВФоне включает и выключает удержание приложения в памяти.
//
// На iOS обычное приложение усыпляют через считаные секунды после
// ухода с экрана, и прокси замолкает вместе с ним. Обход — беззвучный
// звук по кругу с объявленным режимом фоновой работы «audio»; подробно
// он описан в keepalive_ios.m.
//
// Возвращает строку для журнала: пусто, если всё в порядке, и объяснение,
// если удержание не включилось. Молча в таком случае оставлять нельзя —
// пользователь должен знать, что прокси переживёт уход с экрана не
// обязательно.
func удержатьВФоне(включить bool) string {
	if !включить {
		C.TorProxyStopKeepAlive()
		return ""
	}
	if C.TorProxyStartKeepAlive() == 0 {
		return "Удержание в фоне не включилось: прокси может замолчать, " +
			"когда приложение уйдёт с экрана. Держите его открытым."
	}
	return ""
}

// перваяКопия на iPhone всегда истинна: система не запускает второй
// экземпляр приложения, повторный запуск возвращает к тому же.
func перваяКопия(fyne.Window) bool { return true }
