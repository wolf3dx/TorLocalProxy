package main

// Работа с мостами в интерфейсе: файлы и чистка по типам.
//
// Всё это выделено из main, потому что плашка мостов перестала быть
// полем с одной кнопкой. Причина не в желании добавить возможностей, а
// в том, как этими мостами приходится пользоваться: на мобильной сети
// один тип глушат, другой проходит, и человек держит под рукой сразу
// несколько наборов. Значит, наборы надо откуда-то брать, куда-то
// складывать и уметь выбрасывать по одному, не задевая остальные.

import (
	"fmt"
	"io"
	"strings"

	"fyne.io/fyne/v2"
	"fyne.io/fyne/v2/container"
	"fyne.io/fyne/v2/dialog"
	"fyne.io/fyne/v2/layout"
	"fyne.io/fyne/v2/storage"

	"gitlab.com/vkandreevich/torlocalproxy/core/bridges"
)

// ПределФайлаМостов — сколько байт читаем из выбранного файла.
//
// Список мостов — это единицы килобайт. Ограничение стоит не от
// жадности, а чтобы случайно выбранный фильм не уехал целиком в поле
// ввода и не подвесил приложение на телефоне.
const ПределФайлаМостов = 256 * 1024

// загрузитьИзФайла показывает выбор файла и вписывает его содержимое в
// поле мостов.
//
// Выбор идёт через диалог Fyne, а не через путь: на Android и iOS у
// приложения нет доступа к чужим каталогам по пути, файл приходит от
// системы уже открытым.
func (э *экран) загрузитьИзФайла(окно fyne.Window, сохранить func(string) error) {
	выбор := dialog.NewFileOpen(func(файл fyne.URIReadCloser, err error) {
		if err != nil {
			сообщить(окно, "Файл не открылся: "+err.Error())
			return
		}
		if файл == nil {
			return // человек закрыл диалог
		}
		defer func() { _ = файл.Close() }()

		данные, err := io.ReadAll(io.LimitReader(файл, ПределФайлаМостов))
		if err != nil {
			сообщить(окно, "Файл не прочитался: "+err.Error())
			return
		}

		годные, _ := bridges.Parse(string(данные))
		if len(годные) == 0 {
			сообщить(окно, "В файле не нашлось ни одного моста. "+
				"Проверьте, что это тот файл, который присылал BridgeDB.")
			return
		}

		// Добавляем к тому, что уже есть, а не заменяем: наборы разных
		// типов набираются по одному, и затирать прежние — ровно то,
		// чего человек не ждёт. Замена делается кнопкой чистки.
		э.разложитьПоТипам(объединить(э.текстМостов(), string(данные)))
		if err := сохранить(э.текстМостов()); err != nil {
			сообщить(окно, "Не сохранилось: "+err.Error())
			return
		}
		э.обновитьПодписи()
		окно.Canvas().Unfocus()
		сообщить(окно, fmt.Sprintf("Добавлено мостов: %d (%s)",
			len(годные), strings.Join(bridges.Counts(годные), ", ")))
	}, окно)
	выбор.SetFilter(storage.NewExtensionFileFilter([]string{".txt", ".text", ""}))
	выбор.Show()
}

// сохранитьВФайл выгружает содержимое поля в выбранный файл.
//
// Нужно не для порядка на диске: мосты приходят по одному письму, а
// живут долго, и когда приложение переставляют или ставят на второе
// устройство, набор проще перенести файлом, чем собирать заново.
func (э *экран) сохранитьВФайл(окно fyne.Window) {
	if strings.TrimSpace(э.текстМостов()) == "" {
		сообщить(окно, "Сохранять нечего: мостов нет ни в одном поле")
		return
	}

	выбор := dialog.NewFileSave(func(файл fyne.URIWriteCloser, err error) {
		if err != nil {
			сообщить(окно, "Файл не создался: "+err.Error())
			return
		}
		if файл == nil {
			return
		}
		defer func() { _ = файл.Close() }()

		текст := strings.TrimRight(э.текстМостов(), "\r\n") + "\n"
		if _, err := файл.Write([]byte(текст)); err != nil {
			сообщить(окно, "Не записалось: "+err.Error())
			return
		}
		сообщить(окно, "Мосты сохранены в "+файл.URI().Name())
	}, окно)
	выбор.SetFileName("bridges.txt")
	выбор.Show()
}

// контейнерСтолбцом собирает кнопки в столбик. Обёртка ради читаемости
// вызова выше: container.NewVBox принимает переменное число доводов, а
// у нас готовый срез.
func контейнерСтолбцом(объекты []fyne.CanvasObject) fyne.CanvasObject {
	return container.New(layout.NewVBoxLayout(), объекты...)
}

// объединить складывает два набора мостов, не плодя повторов.
//
// Повторы приходят сами: письмо от BridgeDB нередко присылают дважды, а
// файл с мостами дописывают. tor от дубликата не сломается, но список в
// поле становится нечитаемым, а подпись «мостов: 8» при четырёх
// настоящих — прямой обман.
func объединить(было, добавляемое string) string {
	основа := strings.TrimSpace(было)
	if основа == "" {
		return strings.TrimSpace(добавляемое)
	}

	уже := make(map[string]bool)
	for _, мост := range первый(bridges.Parse(основа)) {
		уже[мост.Short()] = true
	}

	строки := []string{основа}
	for _, строка := range strings.Split(добавляемое, "\n") {
		мост, err := bridges.ParseLine(строка)
		if err != nil {
			continue // посторонний текст из второго файла не тащим
		}
		if уже[мост.Short()] {
			continue
		}
		уже[мост.Short()] = true
		строки = append(строки, strings.TrimSpace(строка))
	}
	return strings.Join(строки, "\n")
}

// первый нужен, чтобы взять только мосты из пары «мосты, беды».
func первый(мосты []bridges.Bridge, _ []string) []bridges.Bridge { return мосты }
