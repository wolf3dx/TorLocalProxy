package main

import (
	"fmt"
	"strings"
)

// Автозапуск: приложение поднимается само при входе в систему и, если
// попросили, сразу поднимает прокси.
//
// Зачем это понадобилось. Прокси нужен не сам по себе — его вписывают в
// настройки других программ. После перезагрузки те программы стартуют
// как ни в чём не бывало и упираются в закрытый порт 9050: приложение
// ещё не запущено. Человек узнаёт об этом по отказу чужой программы, а
// не по виду нашего окна.
//
// Способ у каждой системы свой, и ни один не требует прав
// администратора — всё пишется в пользовательский профиль:
//
//	Windows — значение в реестре HKCU\…\CurrentVersion\Run;
//	macOS   — агент входа ~/Library/LaunchAgents/<id>.plist;
//	Linux   — файл ~/.config/autostart/<имя>.desktop (XDG).
//
// Общее здесь — сборка текста этих файлов и разбор аргументов. Запись
// на диск и в реестр — в autostart_<система>.go.

// ИмяАвтозапуска — под ним запись видна пользователю: в «Автозагрузке»
// диспетчера задач Windows, в списке объектов входа macOS, в
// «Автоматически запускаемых приложениях» GNOME.
const ИмяАвтозапуска = "TorLocalProxy"

// ФлагСкрыто говорит запускаемому приложению не показывать окно.
//
// При входе в систему окна лезут на передний план все разом, и наше там
// ни к чему: от него нужен работающий прокси, а не вид. С этим флагом
// приложение уходит в значок у часов сразу, минуя показ окна.
//
// Флаг нарочно ASCII и нарочно один: он попадает в реестр, в plist и в
// .desktop, которые читают чужие программы.
const ФлагСкрыто = "--hidden"

// скрытыйЗапускЗапрошен ищет флаг среди аргументов командной строки.
func скрытыйЗапускЗапрошен(аргументы []string) bool {
	for _, арг := range аргументы {
		if арг == ФлагСкрыто {
			return true
		}
	}
	return false
}

// команднаяСтрока собирает «путь + флаг» с кавычками вокруг пути.
//
// Кавычки обязательны: путь к приложению почти наверняка содержит
// пробел (Program Files, Applications, имя пользователя), и без них
// система разобрала бы его как несколько аргументов.
func команднаяСтрока(путь string) string {
	return `"` + путь + `" ` + ФлагСкрыто
}

// текстPlist — агент входа macOS.
//
// RunAtLoad означает «запустить при загрузке агента», а агенты из
// ~/Library/LaunchAgents загружаются при входе пользователя в систему —
// то есть ровно один раз, как нам и надо. KeepAlive не ставим: иначе
// launchd поднимал бы приложение заново каждый раз, когда человек сам
// его закрыл.
func текстPlist(путь string) string {
	return fmt.Sprintf(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>Label</key>
	<string>%s</string>
	<key>ProgramArguments</key>
	<array>
		<string>%s</string>
		<string>%s</string>
	</array>
	<key>RunAtLoad</key>
	<true/>
</dict>
</plist>
`, ИдПриложения, экранироватьXML(путь), ФлагСкрыто)
}

// текстDesktopEntry — файл автозапуска по стандарту XDG. Его читают все
// распространённые оболочки Linux: GNOME, KDE, XFCE и прочие.
//
// X-GNOME-Autostart-enabled оставлен ради GNOME: без него запись в его
// собственном списке автозапуска выглядит выключенной.
func текстDesktopEntry(путь string) string {
	return fmt.Sprintf(`[Desktop Entry]
Type=Application
Name=%s
Comment=Локальный прокси к сети Tor
Exec=%s
Terminal=false
X-GNOME-Autostart-enabled=true
`, ИмяАвтозапуска, команднаяСтрока(путь))
}

// экранироватьXML прячет символы, на которых разбор plist споткнулся бы.
// В пути к приложению они маловероятны, но путь приходит из файловой
// системы, а не от нас.
func экранироватьXML(текст string) string {
	return strings.NewReplacer(
		"&", "&amp;",
		"<", "&lt;",
		">", "&gt;",
	).Replace(текст)
}
