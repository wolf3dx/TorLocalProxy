//go:build !android && !ios

package main

import (
	"os"

	"fyne.io/fyne/v2"
	"fyne.io/fyne/v2/driver/desktop"
)

// стартоватьСкрытно — надо ли запуститься без окна, сразу в значок у
// часов. Так приложение ведёт себя при входе в систему: запись
// автозапуска добавляет к пути флаг, и окно не лезет на передний план
// среди всего, что открывается в ту же минуту.
//
// Второе условие важнее первого. Без значка в трее скрытое приложение
// превратилось бы в процесс, который невозможно ни увидеть, ни закрыть:
// окна нет, значка нет. Трей есть не во всякой оболочке Linux, поэтому
// там, где его нет, флаг просто не слушаем и показываем окно.
func стартоватьСкрытно(приложение fyne.App) bool {
	if !скрытыйЗапускЗапрошен(os.Args) {
		return false
	}
	_, естьТрей := приложение.(desktop.App)
	return естьТрей
}
