// Команда torproxy — мини-прокси для телефона и компьютера.
//
// Одно окно с четырьмя плашками: состояние подключения, поле мостов,
// журнал и адрес прокси, который вписывают в чужие приложения. Браузера
// нет и не предполагается.
//
// Один и тот же код собирается в окно на компьютере, в APK для Android
// и в приложение для iPhone. Различия заперты в двух парах файлов:
//
//	runtime_*  — где взять tor. На компьютере его ищут по системе, на
//	             Android он лежит в каталоге нативных библиотек пакета
//	             (единственном месте, откуда приложению разрешено
//	             запускать посторонний код), на iOS дочерние процессы
//	             запрещены совсем и tor линкуется библиотекой внутрь.
//	platform_* — как выжить в фоне. На компьютере окно уходит в значок
//	             у часов, на Android держит служба переднего плана, на
//	             iOS — беззвучный звук по кругу, потому что штатного
//	             способа там нет.
package main

import (
	"context"
	"fmt"
	"log"
	"os"
	"strings"
	"time"

	"fyne.io/fyne/v2"
	"fyne.io/fyne/v2/app"
	"fyne.io/fyne/v2/container"
	"fyne.io/fyne/v2/dialog"
	"fyne.io/fyne/v2/theme"
	"fyne.io/fyne/v2/widget"

	"gitlab.com/vkandreevich/torlocalproxy/core"
	"gitlab.com/vkandreevich/torlocalproxy/core/service"
)

// ИдПриложения нужен Fyne, чтобы выделить приложению своё хранилище.
// На Android от него зависит каталог, куда лягут состояние tor и мосты.
const ИдПриложения = "com.vkandreevich.torlocalproxy"

// ПортProxy — порт локального прокси. Он постоянный, а не выбирается
// системой: адрес вписывают в настройки других программ один раз, и он
// не должен меняться от запуска к запуску. 9050 — тот же порт, что у
// Tor Browser и у Orbot, его же ожидают готовые инструкции в интернете.
const ПортProxy = 9050

// ПортHTTP — порт HTTP-прокси поверх того же тора.
//
// Нужен там, где SOCKS5 вписать некуда: программы нередко знают только
// HTTP-прокси, а системные настройки Wi-Fi на iOS — тем более, SOCKS в
// них нет вовсе. 8118 — традиционный порт Privoxy, того самого, что
// десятки лет ставили рядом с тором ровно для этого.
const ПортHTTP = 8118

func main() {
	приложение := app.NewWithID(ИдПриложения)
	// Тема — сохранённый оттенок «Луковицы» (по умолчанию «Тёплая ночь»).
	применитьТему(приложение, текущаяПалитра(приложение).ключ)

	окно := приложение.NewWindow("TorLocalProxy")

	// Единственность экземпляра — до создания службы: вторая копия не
	// должна поднимать второй tor на том же порту. Если мы не первые,
	// первой копии уже сказано показать окно, и нам остаётся тихо выйти.
	if !перваяКопия(окно) {
		return
	}

	каталог := каталогСостояния(приложение)
	служба, err := service.New(service.Options{
		StateDir:  каталог,
		SocksPort: ПортProxy,
		HTTPPort:  ПортHTTP,
		Runtime:   создатьЗапускTor(каталог),
	})
	if err != nil {
		окно.SetContent(widget.NewLabel("Не удалось подготовить приложение:\n" + err.Error()))
		окно.ShowAndRun()
		return
	}

	экран := собратьЭкран(окно, служба)
	окно.SetContent(экран.корень)

	// Мосты из прошлого запуска — чтобы не вставлять их каждый раз.
	if сохранённые, err := служба.LoadBridges(); err == nil && сохранённые != "" {
		экран.разложитьПоТипам(сохранённые)
		// Мосты уже набраны — запираем, чтобы не задеть их случайно.
		экран.заблокировать(окно)
	}

	// Подключение при запуске: включается переменной окружения. Нужно
	// для проверок без участия человека и для случаев, когда прокси
	// должен подниматься сам, без нажатия кнопки.
	//
	// Вешается на событие «приложение запущено», а не запускается сразу:
	// до старта цикла отрисовки обновления виджетов теряются, и окно
	// показывало бы «ВЫКЛЮЧЕНО» при работающем прокси.
	if os.Getenv("TORPROXY_AUTOCONNECT") != "" {
		приложение.Lifecycle().SetOnStarted(func() {
			go func() {
				текст, _ := служба.LoadBridges()
				_ = служба.Connect(context.Background(), текст,
					наблюдатель{экран: экран, окно: окно, служба: служба})
			}()
		})
	}

	// Поведение при закрытии платформозависимо: на компьютере окно
	// уходит в трей, чтобы прокси продолжал отвечать, на телефоне этим
	// занимается служба переднего плана.
	настроитьПлатформу(приложение, окно, служба)

	// Проверка обновлений — в фоне, чтобы не задерживать показ окна.
	// Найдёт версию новее — сама покажет баннер сверху.
	экран.запуститьПроверкуОбновлений(окно, приложение, служба)

	окно.ShowAndRun()
}

// экран держит виджеты, которые обновляются по ходу подключения.
type экран struct {
	корень      fyne.CanvasObject
	состояние   *widget.Label
	фаза        *widget.Label
	полоса      *widget.ProgressBar
	поля        map[string]*полеМостов
	стопкаПолей *fyne.Container
	// прокруткаПлашек нужна, чтобы подкрутить список к полю ввода,
	// когда его закрывает экранная клавиатура.
	прокруткаПлашек *container.Scroll
	выборТипа       *widget.Select
	текущийТип      string
	// Замок поля мостов: пока заперто, поля недоступны для правки, а
	// кнопки, меняющие содержимое, погашены. Отпирается кнопкой.
	заблокировано    bool
	кнопкаБлокировки *widget.Button
	кнопкиПравки     []*widget.Button
	адрес            *адреснаяСтрока
	адресHTTP        *адреснаяСтрока
	плашкаМостов     *widget.Card
	// Чип «мосты · тип · N» на главном экране: открывает экран мостов.
	чипМостов   *чип
	корнеМостов fyne.CanvasObject
	// Зелёная точка рядом с подписью состояния — видна, когда включено.
	точкаСост *точка
	коло      *колоКнопка
	цепочка   *контурнаяКнопка

	// Баннер обновления. Скрыт, пока проверка не найдёт версию новее:
	// тогда наверху окна появляется строка с версией и кнопкой.
	баннерОбн *fyne.Container
	меткаОбн  *widget.Label
	кнопкаОбн *widget.Button
}

func собратьЭкран(окно fyne.Window, служба *service.Service) *экран {
	э := &экран{}

	// ---- Баннер обновления (сверху, скрыт по умолчанию) -------------
	// Появляется первой плашкой, когда проверка находит версию новее.
	// Пока обновления нет — не показывается вовсе, места не занимает.
	э.меткаОбн = widget.NewLabelWithStyle("", fyne.TextAlignLeading,
		fyne.TextStyle{Bold: true})
	э.кнопкаОбн = widget.NewButtonWithIcon("Обновиться", theme.DownloadIcon(), nil)
	э.кнопкаОбн.Importance = widget.HighImportance
	э.баннерОбн = container.NewBorder(nil, nil, nil, э.кнопкаОбн, э.меткаОбн)
	э.баннерОбн.Hide()

	// ---- Шапка: имя приложения и переключатель темы ------------------
	// Кнопка по кругу меняет оттенок «Луковицы» (Тёплая ночь → Янтарный
	// день → Терракота) и запоминает выбор. Текущий оттенок — на кнопке.
	кнопкаТемы := widget.NewButtonWithIcon("", theme.ColorPaletteIcon(), func() {
		след := следующаяПалитра(текущаяПалитра(fyne.CurrentApp()).ключ)
		применитьТему(fyne.CurrentApp(), след.ключ)
	})
	кнопкаТемы.Importance = widget.LowImportance
	версия := widget.NewLabelWithStyle(core.Version, fyne.TextAlignTrailing, fyne.TextStyle{})
	шапка := container.NewBorder(nil, nil,
		widget.NewLabelWithStyle("TorLocalProxy", fyne.TextAlignLeading, fyne.TextStyle{Bold: true}),
		container.NewHBox(версия, кнопкаТемы))

	// ---- Плашка 1: состояние подключения ----------------------------
	э.состояние = widget.NewLabelWithStyle("ВЫКЛЮЧЕНО", fyne.TextAlignCenter,
		fyne.TextStyle{Bold: true})
	э.фаза = widget.NewLabelWithStyle("Не подключено", fyne.TextAlignCenter, fyne.TextStyle{})
	э.полоса = widget.NewProgressBar()
	э.полоса.Hide()

	// Герой «Луковицы»: кольца и есть кнопка подключения.
	э.коло = новоеКоло(func() { э.переключить(окно, служба) })
	э.точкаСост = новаяТочка()
	э.точкаСост.Hide() // зажигается, когда подключено
	герой := container.NewVBox(
		container.NewPadded(container.NewCenter(э.коло)),
		э.состояние,
		container.NewCenter(container.NewHBox(э.точкаСост, э.фаза)),
	)

	// ---- Плашка 4: адрес прокси -------------------------------------
	// Идёт второй сверху не случайно: это то, ради чего приложение и
	// нужно. Пользователь возвращается сюда каждый раз, когда настраивает
	// очередную программу.
	// Адреса — своей строкой: мелкая подпись, крупный моноширинный
	// адрес и иконка копирования справа, как в макете.
	э.адрес = новаяАдреснаяСтрока("SOCKS5", func() { скопировать(окно, э.адрес.значение) })

	// Второй адрес — для тех, кто SOCKS5 не умеет. Таких много: у
	// многих программ в настройках только HTTP-прокси, а на iPhone
	// системные настройки Wi-Fi знают исключительно его.
	э.адресHTTP = новаяАдреснаяСтрока("HTTP", func() { скопировать(окно, э.адресHTTP.значение) })

	// ---- Плашка 2: мосты --------------------------------------------
	//
	// По полю на каждый тип: набор каждого добывается отдельно, и в
	// общей простыне не видно, сколько чего лежит. Тип выбирается
	// списком — пять вкладок с названиями не влезают в ширину телефона.
	сохранитьМосты := func(текст string) error { return служба.SaveBridges(текст) }

	поляМостов := э.собратьПоляМостов(окно)

	// Шесть кнопок по три в ряд, без иконок: подписи короткие, и втроём
	// они укладываются в ширину телефона. С иконками не укладывались —
	// проверено, обрезалась третья.
	разложить := э.кнопкаРазложить(окно, сохранитьМосты)
	встроенные := э.кнопкаВстроенные(окно, сохранитьМосты)
	изФайла := э.кнопкаИзФайла(окно, сохранитьМосты)
	очистить := э.кнопкаОчистить(окно, сохранитьМосты)
	// Кнопки, которые меняют содержимое полей, гаснут вместе с замком:
	// пока заперто, менять мосты нельзя ни руками, ни кнопкой. «Сохранить»
	// и «В файл» ничего не портят и остаются доступны.
	э.кнопкиПравки = []*widget.Button{разложить, встроенные, изФайла, очистить}
	кнопки := container.NewVBox(
		container.NewGridWithColumns(3,
			разложить,
			э.кнопкаСохранить(окно, сохранитьМосты),
			встроенные,
		),
		container.NewGridWithColumns(3,
			изФайла,
			э.кнопкаВФайл(окно),
			очистить,
		),
	)

	э.плашкаМостов = widget.NewCard("Мосты", "", container.NewVBox(
		поляМостов,
		кнопки,
	))
	// Чип мостов на главном: подпись ставит обновитьПодписи.
	э.чипМостов = новыйЧип("мосты — не заданы", func() {
		if э.корнеМостов != nil {
			окно.SetContent(э.корнеМостов)
		}
	})

	э.обновитьПодписи()
	// Свежий запуск с пустыми полями — открыто, чтобы сразу вписать мосты.
	// Если из прошлого запуска что-то подгрузится, main запрёт замок.
	э.применитьБлокировку(окно)

	// ---- Проверка выхода --------------------------------------------
	// Доказательство, что прокси не просто поднялся, а уводит трафик
	// через Tor. Отдельной строкой во всю ширину: рядом с журналом в две
	// колонки подпись обрезалась бы на телефоне.
	проверитьIP := widget.NewButtonWithIcon("Проверить IP", theme.SearchIcon(), func() {
		проверитьВыходВОкне(окно, служба)
	})

	// ---- Плашка 3: журнал -------------------------------------------
	журнал := widget.NewButtonWithIcon("Посмотреть журнал", theme.DocumentIcon(), func() {
		показатьЖурнал(окно, служба)
	})

	// ---- Управление --------------------------------------------------
	э.цепочка = новаяКонтурнаяКнопка("Новая цепочка", func() {
		if err := служба.NewIdentity(context.Background()); err != nil {
			сообщить(окно, err.Error())
			return
		}
		сообщить(окно, "Запрошена новая цепочка")
	})
	э.цепочка.Disable()

	// Плашки прокручиваются, а кнопки управления прибиты к низу окна.
	//
	// Раньше кнопки лежали внутри прокрутки, и это было терпимо, пока
	// плашек было четыре. С появлением плашки HTTP «Подключить» ушла за
	// край экрана телефона: главную кнопку приложения приходилось
	// искать прокруткой. Теперь она на месте всегда.
	// ---- Главный экран: коротко, как в макете ------------------------
	// Мосты не висят простынёй: вместо них чип, он открывает свой экран.
	плашки := container.NewVBox(
		шапка,
		э.баннерОбн,
		герой,
		э.адрес,
		э.адресHTTP,
		container.NewHBox(э.чипМостов),
	)
	// Подключение переехало на кольцо — внизу только «Новая цепочка».
	управление := container.NewPadded(э.цепочка)
	э.корень = container.NewPadded(container.NewBorder(
		nil, управление, nil, nil, container.NewVScroll(плашки),
	))

	// ---- Экран мостов: то же оформление, открывается по чипу ---------
	назад := widget.NewButtonWithIcon("Назад", theme.NavigateBackIcon(), func() {
		окно.SetContent(э.корень)
	})
	назад.Importance = widget.LowImportance
	шапкаМостов := container.NewBorder(nil, nil, назад, nil,
		widget.NewLabelWithStyle("Мосты", fyne.TextAlignCenter, fyne.TextStyle{Bold: true}))
	// Эту прокрутку подкручивает экранная клавиатура: поля мостов здесь.
	э.прокруткаПлашек = container.NewVScroll(container.NewVBox(
		э.плашкаМостов,
		container.NewGridWithColumns(2, проверитьIP, журнал),
	))
	э.корнеМостов = container.NewPadded(container.NewBorder(
		шапкаМостов, nil, nil, nil, э.прокруткаПлашек,
	))
	return э
}

// переключить подключает или отключает — в зависимости от того, где мы
// сейчас.
func (э *экран) переключить(окно fyne.Window, служба *service.Service) {
	if служба.State() == service.StateConnected {
		_ = служба.Disconnect()
		return
	}
	if служба.State() == service.StateConnecting {
		_ = служба.Disconnect()
		return
	}

	текстМостов := э.текстМостов()
	// Сохраняем сразу: пользователь вставил мосты и нажал «Подключить»,
	// нажимать ещё и «Сохранить» он не обязан.
	if err := служба.SaveBridges(текстМостов); err != nil {
		log.Println("мосты не сохранились:", err)
	}

	// Connect блокирующий, поэтому уходим в отдельную горутину: иначе
	// окно замрёт на всё время подключения.
	go func() {
		err := служба.Connect(context.Background(), текстМостов,
			наблюдатель{экран: э, окно: окно, служба: служба})
		if err != nil {
			fyne.Do(func() { сообщить(окно, err.Error()) })
		}
	}()
}

// наблюдатель переносит события службы в виджеты.
//
// Все обращения к интерфейсу завёрнуты в fyne.Do: служба зовёт нас из
// своей горутины, а трогать виджеты можно только из потока интерфейса.
type наблюдатель struct {
	экран  *экран
	окно   fyne.Window
	служба *service.Service
}

func (н наблюдатель) OnBootstrap(percent int, phase string) {
	fyne.Do(func() {
		н.экран.коло.установить(service.StateConnecting, percent)
		н.экран.фаза.SetText(fmt.Sprintf("%d%% — %s", percent, phase))
	})
}

func (н наблюдатель) OnLog(string) {
	// Строки уже копятся в службе; кнопка журнала читает их оттуда.
}

func (н наблюдатель) OnState(state string) {
	// Удержание в фоне включается по факту работы прокси, а не по
	// открытию приложения: пока подключения нет, держать процесс в
	// памяти незачем. Значимо это только на iPhone, на остальных
	// платформах вызов пустой.
	if предупреждение := удержатьВФоне(state == service.StateConnected); предупреждение != "" {
		сообщить(н.окно, предупреждение)
	}

	fyne.Do(func() {
		switch state {
		case service.StateConnecting:
			н.экран.состояние.SetText("ПОДКЛЮЧЕНИЕ")
			н.экран.коло.установить(service.StateConnecting, н.экран.коло.процент)
			н.экран.точкаСост.Hide()
			н.экран.цепочка.Disable()

		case service.StateConnected:
			н.экран.состояние.SetText("ВКЛЮЧЕНО")
			н.экран.фаза.SetText("трафик идёт через Tor")
			// Ради этой строки всё и затевалось: её вписывают в чужие
			// приложения. Порт каждый раз новый — его выбирает tor.
			н.экран.адрес.SetText(н.служба.SocksAddress())
			if адрес := н.служба.HTTPAddress(); адрес != "" {
				н.экран.адресHTTP.SetText(адрес)
			} else {
				н.экран.адресHTTP.SetText("не поднялся — см. журнал")
			}
			н.экран.коло.установить(service.StateConnected, 100)
			н.экран.точкаСост.Show()
			н.экран.цепочка.Enable()

		case service.StateFailed:
			н.экран.состояние.SetText("ОШИБКА")
			н.экран.фаза.SetText("Подробности — в журнале")
			н.экран.коло.установить(service.StateFailed, 0)
			н.экран.точкаСост.Hide()
			н.экран.цепочка.Disable()
			н.экран.адрес.SetText("—")
			н.экран.адресHTTP.SetText("—")

		default:
			н.экран.состояние.SetText("ВЫКЛЮЧЕНО")
			н.экран.фаза.SetText("Не подключено")
			н.экран.коло.установить(service.StateIdle, 0)
			н.экран.точкаСост.Hide()
			н.экран.цепочка.Disable()
			н.экран.адрес.SetText("—")
			н.экран.адресHTTP.SetText("—")
		}
	})
}

// показатьЖурнал открывает журнал — ту самую кнопку «понять, что не
// так».
//
// Текст выводится одной меткой в прокрутке, а не списком. Список здесь
// уже стоил падения: его ScrollToBottom обращается к внутренней
// прокрутке, которой до отрисовки виджета не существует, и приложение
// уходило в nil pointer dereference, унося с собой tor. Прокрутка
// сдвигается только после того, как окно показано.
func показатьЖурнал(окно fyne.Window, служба *service.Service) {
	строки := служба.Log()
	if len(строки) == 0 {
		сообщить(окно, "Журнал пуст — подключение ещё не начиналось")
		return
	}

	текст := widget.NewLabel(strings.Join(строки, "\n"))
	текст.TextStyle = fyne.TextStyle{Monospace: true}
	текст.Wrapping = fyne.TextWrapWord

	прокрутка := container.NewVScroll(текст)

	// Размер берём от самого окна: на телефоне жёстко заданный может
	// оказаться больше экрана.
	размер := окно.Canvas().Size()
	прокрутка.SetMinSize(fyne.NewSize(размер.Width*0.9, размер.Height*0.7))

	окноЖурнала := dialog.NewCustom("Журнал подключения", "Закрыть", прокрутка, окно)
	окноЖурнала.Show()

	// Причина отказа всегда в конце, поэтому показываем хвост — но уже
	// после Show, когда прокрутке есть что двигать.
	прокрутка.ScrollToBottom()
}

// проверитьВыходВОкне спрашивает check.torproject.org, кто мы снаружи, и
// показывает ответ. Это кнопка «Проверить IP».
//
// Запрос идёт через наш же прокси и потому не мгновенный: пока он идёт,
// показываем окошко ожидания, чтобы человек не жал кнопку повторно.
// Сам запрос — в отдельной горутине: иначе окно замрёт на всё время.
func проверитьВыходВОкне(окно fyne.Window, служба *service.Service) {
	if служба.State() != service.StateConnected {
		сообщить(окно, "Сначала подключитесь — проверять нечего")
		return
	}

	ожидание := dialog.NewCustomWithoutButtons("Проверка",
		widget.NewLabel("Спрашиваю check.torproject.org…"), окно)
	ожидание.Show()

	go func() {
		ctx, отмена := context.WithTimeout(context.Background(), 95*time.Second)
		defer отмена()

		ip, черезTor, err := служба.CheckExitIP(ctx)

		fyne.Do(func() {
			ожидание.Hide()
			switch {
			case err != nil:
				сообщить(окно, "Проверить не удалось: "+err.Error())
			case черезTor:
				сообщить(окно, "Трафик идёт через Tor.\nВыходной адрес: "+ip)
			default:
				сообщить(окно, "Внимание: выход НЕ через Tor.\nВидимый адрес: "+ip)
			}
		})
	}()
}

// скопировать кладёт адрес в буфер обмена. Отдельной функцией — потому
// что адресов теперь два, а поведение у кнопок одно.
func скопировать(окно fyne.Window, текст string) {
	if текст == "" || текст == "—" {
		сообщить(окно, "Прокси ещё не поднят")
		return
	}
	окно.Clipboard().SetContent(текст)
	сообщить(окно, "Адрес скопирован")
}

func сообщить(окно fyne.Window, текст string) {
	dialog.ShowInformation("TorLocalProxy", текст, окно)
}
