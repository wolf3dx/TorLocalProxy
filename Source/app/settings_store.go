package main

import (
	"encoding/json"
	"os"
	"path/filepath"
	"sync"
)

// Своё хранилище настроек вместо Preferences у Fyne.
//
// Fyne пишет настройки только в профиль пользователя и другого места не
// предлагает. Нам нужно рядом с приложением (см. portable_desktop.go),
// поэтому держим свой файл — settings.json в каталоге данных. Формат
// тот же плоский JSON, что у Fyne, чтобы старые настройки читались без
// перевода.
//
// Ключей всего два: выбранная тема и галочка автоподключения. Заводить
// ради них базу незачем, но и терять их при каждом запуске нельзя.

// ИмяФайлаНастроек — рядом с каталогом tor, в корне данных приложения.
const ИмяФайлаНастроек = "settings.json"

type хранилище struct {
	мьютекс  sync.Mutex
	путь     string
	значения map[string]any
}

// настройки — единственное на приложение. Заполняется открытьНастройки
// при запуске; до этого все чтения возвращают значения по умолчанию, а
// записи пропадают молча (такого быть не должно, но падать из-за
// настроек — хуже).
var настройки = &хранилище{значения: map[string]any{}}

// источникПереноса — откуда забирать настройки прошлой версии. Вынесен
// переменной ради тестов: иначе они читали бы настоящий профиль того,
// кто запустил сборку, и зависели бы от его темы.
var источникПереноса = прежнийКаталог

// открытьНастройки читает файл из каталога данных. Если файла нет
// вовсе, пробует забрать настройки из прежнего места в профиле — чтобы
// после переезда человек не выбирал тему и галочки заново.
//
// Именно «нет вовсе»: существующий файл главнее прежнего места, даже
// если он пуст или испорчен. Иначе человек, однажды сбросивший
// настройки, получал бы их обратно из профиля при каждом запуске.
func открытьНастройки(корень string) {
	настройки.мьютекс.Lock()
	defer настройки.мьютекс.Unlock()

	настройки.путь = filepath.Join(корень, ИмяФайлаНастроек)
	if _, err := os.Stat(настройки.путь); err == nil {
		настройки.значения = прочитатьJSON(настройки.путь)
		return
	}

	настройки.значения = map[string]any{}
	старый := источникПереноса()
	if старый == "" {
		return
	}
	старые := прочитатьJSON(filepath.Join(старый, "preferences.json"))
	for _, ключ := range []string{ключТемы, ключАвтоподключения} {
		if значение, есть := старые[ключ]; есть {
			настройки.значения[ключ] = значение
		}
	}
	if len(настройки.значения) > 0 {
		настройки.сохранить()
	}
}

func прочитатьJSON(путь string) map[string]any {
	значения := map[string]any{}
	if путь == "" {
		return значения
	}
	данные, err := os.ReadFile(путь)
	if err != nil {
		return значения
	}
	if err := json.Unmarshal(данные, &значения); err != nil {
		return map[string]any{}
	}
	return значения
}

// сохранить вызывается под уже взятым замком.
func (х *хранилище) сохранить() {
	if х.путь == "" {
		return
	}
	данные, err := json.Marshal(х.значения)
	if err != nil {
		return
	}
	if err := os.MkdirAll(filepath.Dir(х.путь), 0o755); err != nil {
		return
	}
	_ = os.WriteFile(х.путь, данные, 0o600)
}

// настройкаСтрока — значение или запасное, если его нет.
func настройкаСтрока(ключ, запасное string) string {
	настройки.мьютекс.Lock()
	defer настройки.мьютекс.Unlock()

	if значение, ок := настройки.значения[ключ].(string); ок && значение != "" {
		return значение
	}
	return запасное
}

// настройкаФлаг — галочка; не выставлена значит «нет».
func настройкаФлаг(ключ string) bool {
	настройки.мьютекс.Lock()
	defer настройки.мьютекс.Unlock()

	значение, _ := настройки.значения[ключ].(bool)
	return значение
}

// записатьНастройку кладёт значение и сразу сохраняет файл: настройки
// меняют раз в год, а потерять их при аварийном закрытии обидно.
func записатьНастройку(ключ string, значение any) {
	настройки.мьютекс.Lock()
	defer настройки.мьютекс.Unlock()

	настройки.значения[ключ] = значение
	настройки.сохранить()
}
