package main

// Кнопки плашки мостов: шесть штук по три в ряд.
//
// Каждая заведена отдельной функцией не ради красоты, а потому что
// раскладка кнопок менялась уже трижды: сначала одна кнопка, потом две,
// потом ряд из трёх с иконками — и тот не влез в ширину телефона.
// Отдельные функции переставляются в любом порядке, а действие при этом
// остаётся на месте.
//
// Подписи короткие и без иконок сознательно: иконка добавляет к кнопке
// половину слова ширины, а втроём в ряд они после этого не укладываются.

import (
	"fmt"

	"fyne.io/fyne/v2"
	"fyne.io/fyne/v2/dialog"
	"fyne.io/fyne/v2/widget"

	"gitlab.com/vkandreevich/torlocalproxy/core/bridges"
)

// кнопкаРазложить раскидывает вставленный текст по полям типов.
//
// Нужна, когда письмо от BridgeDB вставили целиком в одно поле: мосты
// разойдутся по своим типам, а приветствие и подпись отбросятся.
func (э *экран) кнопкаРазложить(окно fyne.Window, сохранить func(string) error) *widget.Button {
	return widget.NewButton("Разложить", func() {
		разобрано, отброшено := э.разложитьПоТипам(э.текстМостов())
		if err := сохранить(э.текстМостов()); err != nil {
			сообщить(окно, "Не сохранилось: "+err.Error())
			return
		}
		окно.Canvas().Unfocus()
		сообщить(окно, fmt.Sprintf(
			"Разобрано мостов: %d, отброшено лишних строк: %d", разобрано, отброшено))
	})
}

// кнопкаСохранить запоминает мосты до следующего запуска.
func (э *экран) кнопкаСохранить(окно fyne.Window, сохранить func(string) error) *widget.Button {
	return widget.NewButton("Сохранить", func() {
		if err := сохранить(э.текстМостов()); err != nil {
			сообщить(окно, "Не сохранилось: "+err.Error())
			return
		}
		э.обновитьПодписи()
		окно.Canvas().Unfocus()
		сообщить(окно, "Мосты сохранены")
	})
}

// кнопкаВстроенные вписывает мосты, которые не нужно заказывать.
//
// У snowflake и meek_lite строка одна на всех, и точно эти строки лежат
// внутри каждого Tor Browser. Это выход, когда obfs4 в сети глушат, а
// своих webtunnel-мостов ещё нет.
func (э *экран) кнопкаВстроенные(окно fyne.Window, сохранить func(string) error) *widget.Button {
	return widget.NewButton("Встроенные", func() {
		э.разложитьПоТипам(объединить(э.текстМостов(), bridges.Builtin()))
		if err := сохранить(э.текстМостов()); err != nil {
			сообщить(окно, "Не сохранилось: "+err.Error())
			return
		}
		окно.Canvas().Unfocus()
		сообщить(окно, "Добавлены snowflake и meek_lite. Нажмите «Подключить».")
	})
}

// кнопкаИзФайла подгружает мосты из текстового файла.
func (э *экран) кнопкаИзФайла(окно fyne.Window, сохранить func(string) error) *widget.Button {
	return widget.NewButton("Из файла", func() {
		э.загрузитьИзФайла(окно, сохранить)
	})
}

// кнопкаВФайл выгружает мосты в текстовый файл.
func (э *экран) кнопкаВФайл(окно fyne.Window) *widget.Button {
	return widget.NewButton("В файл", func() {
		э.сохранитьВФайл(окно)
	})
}

// кнопкаОчистить спрашивает, что убрать: выбранный тип или всё.
//
// Спрашивает, а не чистит молча, ровно по одной причине: наборы мостов
// добываются по одному и стоят человеку времени. Промах по кнопке не
// должен уносить всё сразу.
func (э *экран) кнопкаОчистить(окно fyne.Window, сохранить func(string) error) *widget.Button {
	return widget.NewButton("Очистить", func() {
		тип := э.текущийТип
		var окноВыбора dialog.Dialog

		этот := widget.NewButton("Убрать «"+тип+"»", func() {
			э.поля[тип].SetText("")
			if err := сохранить(э.текстМостов()); err != nil {
				сообщить(окно, "Не сохранилось: "+err.Error())
				return
			}
			э.обновитьПодписи()
			окно.Canvas().Unfocus()
			окноВыбора.Hide()
			сообщить(окно, "Поле «"+тип+"» очищено")
		})

		всё := widget.NewButton("Убрать мосты всех типов", func() {
			э.разложитьПоТипам("")
			if err := сохранить(""); err != nil {
				сообщить(окно, "Не сохранилось: "+err.Error())
				return
			}
			окно.Canvas().Unfocus()
			окноВыбора.Hide()
			сообщить(окно, "Все мосты убраны — подключение пойдёт напрямую")
		})
		всё.Importance = widget.DangerImportance

		окноВыбора = dialog.NewCustom("Что убрать", "Отмена",
			контейнерСтолбцом([]fyne.CanvasObject{этот, всё}), окно)
		окноВыбора.Show()
	})
}
