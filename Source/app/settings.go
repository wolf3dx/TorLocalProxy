package main

import (
	"fyne.io/fyne/v2"
	"fyne.io/fyne/v2/container"
	"fyne.io/fyne/v2/theme"
	"fyne.io/fyne/v2/widget"
)

// Экран настроек: две галочки, от которых зависит, что произойдёт без
// участия человека — при входе в систему и при запуске приложения.
//
// Обе выключены по умолчанию, и это не случайность: приложение, которое
// само прописывается в автозагрузку и само поднимает сеть, никто не
// просил. Включает их человек, и он же видит в настройках системы, что
// именно включено.

// ключАвтоподключения — в настройках Fyne. Хранится рядом с выбранной
// темой, в профиле пользователя.
const ключАвтоподключения = "автоподключение"

// автоподключениеВключено — поднимать ли прокси сразу после запуска.
//
// Переменная окружения TORPROXY_AUTOCONNECT оставлена: ею пользуются
// проверки без участия человека, и она работает, даже когда галочка не
// стоит. Галочка — то же самое для живого пользователя.
func автоподключениеВключено(приложение fyne.App) bool {
	return приложение.Preferences().Bool(ключАвтоподключения)
}

// собратьЭкранНастроек делает отдельный экран — как у мостов, с
// кнопкой «Назад». Диалогом это было бы теснее: пояснения к галочкам
// длиннее самих галочек, а на телефоне диалог ограничен шириной экрана.
func (э *экран) собратьЭкранНастроек(окно fyne.Window, приложение fyne.App) fyne.CanvasObject {
	строки := []fyne.CanvasObject{}

	// ---- Автозапуск при входе в систему -----------------------------
	// Показываем только там, где умеем: на телефоне такой возможности у
	// обычного приложения нет вовсе, и мёртвая галочка там ни к чему.
	if автозапускДоступен() {
		галочка := widget.NewCheck("Запускать при входе в систему", nil)
		галочка.SetChecked(автозапускВключён())
		галочка.OnChanged = func(включить bool) {
			if err := настроитьАвтозапуск(включить); err != nil {
				сообщить(окно, "Не удалось изменить автозапуск:\n"+err.Error())
				// Возвращаем галочку к тому, как есть на самом деле:
				// показывать включённым то, что не включилось, нельзя.
				галочка.SetChecked(автозапускВключён())
			}
		}
		строки = append(строки,
			галочка,
			подпись("Приложение поднимется само и уйдёт в значок у часов, "+
				"не открывая окна. Выключить можно и отсюда, и в настройках "+
				"автозагрузки самой системы."),
		)
	}

	// ---- Подключение сразу при запуске -------------------------------
	авто := widget.NewCheck("Подключаться сразу при запуске", nil)
	авто.SetChecked(автоподключениеВключено(приложение))
	авто.OnChanged = func(включить bool) {
		приложение.Preferences().SetBool(ключАвтоподключения, включить)
	}
	строки = append(строки,
		авто,
		подпись("Прокси начнёт подниматься, как только приложение "+
			"запустится, — с теми мостами, что сохранены. Вместе с "+
			"автозапуском это значит, что после перезагрузки адрес "+
			"127.0.0.1:9050 отвечает без единого нажатия."),
	)

	назад := widget.NewButtonWithIcon("Назад", theme.NavigateBackIcon(), func() {
		окно.SetContent(э.корень)
	})
	назад.Importance = widget.LowImportance
	шапка := container.NewBorder(nil, nil, назад, nil,
		widget.NewLabelWithStyle("Настройки", fyne.TextAlignCenter, fyne.TextStyle{Bold: true}))

	содержимое := container.NewVScroll(container.NewVBox(
		widget.NewCard("Без участия человека", "", container.NewVBox(строки...)),
	))
	return container.NewPadded(container.NewBorder(шапка, nil, nil, nil, содержимое))
}

// подпись — пояснение под галочкой: мельче, тусклее и с переносом по
// словам, чтобы на ширине телефона не уезжало за край.
func подпись(текст string) *widget.Label {
	метка := widget.NewLabel(текст)
	метка.Wrapping = fyne.TextWrapWord
	метка.Importance = widget.LowImportance
	return метка
}
