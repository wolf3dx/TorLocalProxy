//go:build !android && !ios

package main

import (
	"os"
	"path/filepath"
	"runtime"
)

// Переносимость: всё своё носим с собой.
//
// Раньше приложение складывало состояние туда, куда Fyne кладёт его по
// умолчанию, — в профиль пользователя (%USERPROFILE%\AppData\Roaming\fyne
// на Windows, ~/.config/fyne на Linux). Для установленной программы это
// правильно, для распакованной из архива — нет: папку носят с собой на
// флешке, а настройки и мосты остаются на чужой машине.
//
// Хуже того, на доменной машине профиль оказался «C:\Users\Регистратура»,
// и tor об этот путь спотыкается: файлы он открывает однобайтовой
// кодировкой, кириллицу в пути не понимает и выходит, не открыв
// control-порт. Подстраховка в torrun (короткое имя 8.3) выручает не
// всегда — короткие имена на томе могут быть просто отключены, и тогда
// спасает только путь без кириллицы.
//
// Поэтому: если рядом с исполняемым файлом можно писать, вся кухня живёт
// там, в подпапке Data. Если нельзя — приложение положили в Program
// Files, /opt или в /Applications, — остаётся прежнее место в профиле:
// лучше так, чем отказ записи.
//
// Переменные окружения для этого не трогаем: Fyne под Windows строит
// свой путь из USERPROFILE напрямую, и подмена домашнего каталога ради
// одной папки — слишком грубо. Вместо этого Fyne-хранилище просто не
// используется: состояние лежит в нашем каталоге, настройки — в своём
// файле рядом (см. settings_store.go).

// ПапкаДанных — имя подпапки рядом с приложением. Нарочно латиницей и
// без пробелов: внутри неё лежат пути, которые мы отдаём tor.
const ПапкаДанных = "Data"

// папкаРядом возвращает каталог данных около приложения или пустую
// строку, если писать туда нельзя.
func папкаРядом() string {
	файл, err := os.Executable()
	if err != nil {
		return ""
	}
	if настоящий, err := filepath.EvalSymlinks(файл); err == nil {
		файл = настоящий
	}

	каталог := filepath.Join(filepath.Dir(файл), ПапкаДанных)
	if !записываем(каталог) {
		return ""
	}
	return каталог
}

// записываем проверяет каталог делом, а не правами: создаёт его и
// пробует записать файл. Права на сетевых дисках и под политиками
// домена врут, а неудачная запись — нет.
func записываем(каталог string) bool {
	if err := os.MkdirAll(каталог, 0o755); err != nil {
		return false
	}
	проба := filepath.Join(каталог, ".probe")
	if err := os.WriteFile(проба, []byte("ok"), 0o600); err != nil {
		return false
	}
	_ = os.Remove(проба)
	return true
}

// прежнийКаталог — то место в профиле, где всё лежало до переезда.
// Нужен ровно для одного: один раз забрать оттуда тему, галочки и
// мосты, чтобы человек не настраивал заново.
//
// Путь повторяет то, как его считает сам Fyne (internal/app): под
// Windows — из домашнего каталога напрямую, на остальных — через
// каталог настроек пользователя. Повторяем нарочно, вместо обращения к
// Storage(): одно такое обращение создало бы папку в профиле, от
// которой мы и уходим.
func прежнийКаталог() string {
	if runtime.GOOS == "windows" {
		дом, err := os.UserHomeDir()
		if err != nil {
			return ""
		}
		return filepath.Join(дом, "AppData", "Roaming", "fyne", ИдПриложения)
	}
	настройки, err := os.UserConfigDir()
	if err != nil {
		return ""
	}
	return filepath.Join(настройки, "fyne", ИдПриложения)
}
