package main

import (
	"os"
	"path/filepath"

	"fyne.io/fyne/v2"
)

// корневойКаталог — где приложение держит всё своё: состояние tor,
// мосты, настройки.
//
// На компьютере это папка рядом с самим приложением, если туда можно
// писать (см. portable_desktop.go). Не выходит — остаётся хранилище,
// которое выдаёт Fyne: в профиле пользователя на компьютере, в
// песочнице приложения на телефоне.
func корневойКаталог(приложение fyne.App) string {
	if свой := папкаРядом(); свой != "" {
		return свой
	}
	if корень := приложение.Storage().RootURI(); корень != nil {
		return корень.Path()
	}
	// Последняя соломинка: рядом с рабочим каталогом. Сюда попадаем,
	// только если хранилища нет вовсе, — но без каталога нам не жить.
	return "tor-state"
}

// каталогСостояния — подпапка, где живёт сам tor: его данные, журнал,
// файл control-порта и сохранённые мосты.
func каталогСостояния(приложение fyne.App) string {
	return filepath.Join(корневойКаталог(приложение), "tor")
}

// перенестиМосты один раз забирает набранные мосты из прежнего места в
// профиле. Без этого человек, у которого приложение уже работало,
// после обновления увидел бы пустые поля и решил, что всё потерялось.
//
// Переносится только то, что вводили руками. Состояние tor не трогаем:
// оно восстановится само, а весит больше всего остального. Старое за
// собой не удаляем — стирать чужие файлы молча нельзя.
func перенестиМосты(корень string) {
	куда := filepath.Join(корень, "tor", "bridges.txt")
	if _, err := os.Stat(куда); err == nil {
		return // на новом месте уже есть — не затираем
	}
	старый := прежнийКаталог()
	if старый == "" {
		return
	}
	данные, err := os.ReadFile(filepath.Join(старый, "tor", "bridges.txt"))
	if err != nil {
		return // нечего переносить
	}
	if err := os.MkdirAll(filepath.Dir(куда), 0o755); err != nil {
		return
	}
	_ = os.WriteFile(куда, данные, 0o600)
}
