//go:build !android && !ios

package main

import (
	"net"
	"time"

	"fyne.io/fyne/v2"
)

// АдресОднойКопии — локальный порт-замок. Это не прокси: на нём висит
// признак «копия уже работает», и по нему же вторая копия просит первую
// показать окно. Порт нарочно свой, не 9050 и не 8118, чтобы не
// пересекаться с самим прокси и его HTTP-адресом.
const АдресОднойКопии = "127.0.0.1:19050"

// перваяКопия проверяет, что на этом компьютере мы — единственный
// экземпляр, и заодно налаживает канал «показать окно».
//
// Зачем это вообще нужно. Окно на десктопе по крестику не закрывается, а
// прячется в значок у часов — процесс живёт, прокси отвечает. Человек,
// забыв про значок, запускает файл ещё раз, и без защиты поднимается
// вторая копия: два значка в трее и две попытки занять один порт 9050.
//
// Замок — слушающий сокет. Пока приложение работает, порт занят, и
// второй Listen на него не сядет. Это надёжнее файла-замка: сокет
// освобождает сама система, когда процесс умирает, и после аварийного
// завершения не остаётся висеть, как забытый файл с чужим PID внутри.
//
// Заняли порт — мы первая копия: слушаем и по каждому стуку поднимаем
// окно. Порт уже занят — мы вторая копия: стучимся к первой, чтобы она
// показалась, и уходим (возвращаем false).
func перваяКопия(окно fyne.Window) bool {
	слушатель, err := net.Listen("tcp", АдресОднойКопии)
	if err != nil {
		// Порт занят — почти наверняка нашей же первой копией. Стучимся,
		// чтобы она вышла из трея на передний план. Если там вдруг
		// оказался посторонний сервис, вреда нет: он стук не поймёт, а мы
		// всё равно не станем поднимать вторую копию прокси.
		if соединение, e := net.DialTimeout("tcp", АдресОднойКопии, 2*time.Second); e == nil {
			_ = соединение.Close()
		}
		return false
	}

	// Первая копия. Слушаем стуки от будущих запусков: сам факт
	// соединения значит «меня попытались запустить ещё раз — покажись».
	go func() {
		for {
			соединение, err := слушатель.Accept()
			if err != nil {
				return
			}
			_ = соединение.Close()
			fyne.Do(func() {
				окно.Show()
				окно.RequestFocus()
			})
		}
	}()
	return true
}
