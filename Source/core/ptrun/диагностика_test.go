// Разбор отказа — то, что пользователь прочитает в журнале вместо
// молчания. Проверяем не формулировки, а различение случаев: совет при
// закрытом порте и при DPI разный, и перепутать их нельзя.

func TestРазборОтказаБезTCP(t *testing.T) {
	текст := разборОтказа("obfs4", false)
	if !strings.Contains(текст, "TCP") {
		t.Errorf("не сказано, что дело не дошло до TCP: %q", текст)
	}
	if !strings.Contains(текст, "443") {
		t.Errorf("нет совета про порт 443, а это главное при закрытом порте: %q", текст)
	}
	if strings.Contains(текст, "DPI") {
		t.Errorf("про DPI говорить нельзя: соединение не открылось вовсе: %q", текст)
	}
}

func TestРазборОтказаObfs4ПослеTCP(t *testing.T) {
	текст := разборОтказа("obfs4", true)
	if !strings.Contains(текст, "DPI") {
		t.Errorf("оборванное рукопожатие obfs4 — это про DPI: %q", текст)
	}
	for _, совет := range []string{"webtunnel", "snowflake"} {
		if !strings.Contains(текст, совет) {
			t.Errorf("нет совета перейти на %s: %q", совет, текст)
		}
	}
	if strings.Contains(текст, "Возьмите мост на 443") {
		t.Errorf("совет про порт здесь неуместен, порт уже открылся: %q", текст)
	}
}

func TestРазборОтказаДругойТранспорт(t *testing.T) {
	текст := разборОтказа("webtunnel", true)
	if !strings.Contains(текст, "webtunnel") {
		t.Errorf("в тексте должен быть назван сам транспорт: %q", текст)
	}
}

// Список транспортов виден пользователю в тексте ошибки, и он же —
// обещание приложения. Проверяем, что обещаны все четыре: обход
// мобильного DPI держится именно на трёх последних.
func TestSupportedВсеЧетыре(t *testing.T) {
	есть := map[string]bool{}
	for _, имя := range Supported() {
		есть[имя] = true
	}
	for _, нужен := range []string{"obfs4", "webtunnel", "snowflake", "meek_lite"} {
		if !есть[нужен] {
			t.Errorf("транспорт %s не собран, а без него на мобильных сетях "+
				"подключиться может быть нечем; собраны: %v", нужен, Supported())
		}
	}
}

// Транспорты из lyrebird рассказывают о себе через стандартный log:
// snowflake пишет про брокера, NAT и переговоры. Это самые ценные
// строки при разборе отказа, и они должны попадать в журнал
// приложения, а не в стандартный вывод, которого на телефоне не видит
// никто.
func TestСтандартныйЖурналПопадаетВНаш(t *testing.T) {
	var замок sync.Mutex
	var строки []string

	бегун := New(Options{Log: func(строка string) {
		замок.Lock()
		defer замок.Unlock()
		строки = append(строки, строка)
	}})

	// Транспортов не просим: перехват ставится в начале Start, до
	// какой-либо работы, и пустой список для него ничего не меняет.
	if _, err := бегун.Start(nil, t.TempDir()); err != nil {
		t.Fatalf("пустой запуск не должен падать: %v", err)
	}
	// Пустой список выходит раньше перехвата — поднимаем настоящий,
	// иначе проверяли бы не то.
	if _, err := бегун.Start([]string{"obfs4"}, t.TempDir()); err != nil {
		t.Fatalf("obfs4 не поднялся: %v", err)
	}
	t.Cleanup(func() { _ = бегун.Stop() })

	log.Println("проверочная строка из библиотеки")

	замок.Lock()
	defer замок.Unlock()
	for _, строка := range строки {
		if strings.Contains(строка, "проверочная строка из библиотеки") {
			return
		}
	}
	t.Errorf("строка стандартного журнала не дошла до нашего; собрано: %v", строки)
}

// Встроенные мосты приложение предлагает одной кнопкой — значит, их
// транспорты обязаны быть собраны. Проверка связывает два пакета,
// которые иначе разъезжаются молча: строку в список встроенных
// добавить легко, а транспорт к ней забыть — ещё легче.
func TestТранспортыВстроенныхМостовСобраны(t *testing.T) {
	собран := map[string]bool{}
	for _, имя := range Supported() {
		собран[имя] = true
	}

	годные, _ := bridges.Parse(bridges.Builtin())
	транспорты := bridges.Transports(годные)
	if len(транспорты) == 0 {
		t.Fatal("во встроенных мостах не оказалось ни одного транспорта")
	}
	for _, имя := range транспорты {
		if !собран[имя] {
			t.Errorf("встроенный мост требует транспорт %q, которого в сборке нет; "+
				"кнопка «встроенные мосты» выдала бы отказ вместо помощи", имя)
		}
	}
}
