// Package ptrun поднимает pluggable transports внутри нашего процесса.
//
// Обычно obfs4 работает так: tor запускает отдельный исполняемый файл
// lyrebird и разговаривает с ним по SOCKS. Здесь этого файла нет — код
// lyrebird подключён библиотекой, а SOCKS-слушатель поднимаем мы сами.
// Причины две, и обе весомые:
//
//   - На iOS дочерние процессы запрещены совсем, и другого пути там нет
//     (ЛОГИКА.md, раздел 2.1). Один путь для всех платформ дешевле в
//     поддержке, чем два, из которых мобильный проверяется вдвое реже.
//   - Рядом с приложением не нужно класть посторонних исполняемых файлов,
//     а в torrc не остаётся ни одного exec. На Android это вообще
//     единственный вариант: положить исполняемый файл и запустить его из
//     каталога приложения там нельзя.
//
// Что делает слушатель: принимает соединение от tor, забирает из полей
// аутентификации SOCKS параметры моста (cert=, iat-mode=), заворачивает
// исходящее соединение в транспорт и перекачивает байты. Ровно то же
// делает main самого lyrebird — здесь оно вызвано напрямую.
package ptrun

import (
	"errors"
	"fmt"
	"io"
	"log"
	"net"
	"sort"
	"strings"
	"sync"
	"sync/atomic"
	"time"

	pt "gitlab.torproject.org/tpo/anti-censorship/pluggable-transports/goptlib"
	"gitlab.torproject.org/tpo/anti-censorship/pluggable-transports/lyrebird/transports/base"
	"gitlab.torproject.org/tpo/anti-censorship/pluggable-transports/lyrebird/transports/meeklite"
	"gitlab.torproject.org/tpo/anti-censorship/pluggable-transports/lyrebird/transports/obfs4"
	"gitlab.torproject.org/tpo/anti-censorship/pluggable-transports/lyrebird/transports/snowflake"
	"gitlab.torproject.org/tpo/anti-censorship/pluggable-transports/lyrebird/transports/webtunnel"

	"gitlab.com/vkandreevich/torlocalproxy/core/torconf"
)

// Plugin — поднятый транспорт: что он обслуживает и на каком адресе
// слушает. Тип общий с torconf, чтобы адрес попадал в torrc без
// перекладывания.
type Plugin = torconf.Plugin

// Runner поднимает и останавливает транспорты.
type Runner interface {
	// Start поднимает слушателей для перечисленных транспортов и
	// возвращает их адреса. stateDir нужен самим транспортам: obfs4
	// хранит там своё состояние.
	Start(transports []string, stateDir string) ([]Plugin, error)
	Stop() error
}

// Options настраивает Runner.
type Options struct {
	// Log — куда писать о происходящем. Пусто — молчать. Через него
	// строки попадают в журнал приложения: без них отказ транспорта
	// выглядит как «tor застрял на 10 %».
	Log func(string)
}

// Local — реализация на библиотеке lyrebird, в этом же процессе.
type Local struct {
	настройки Options

	мьютекс    sync.Mutex
	слушатели  []net.Listener
	ожидание   sync.WaitGroup
	остановлен bool
}

var _ Runner = (*Local)(nil)

// таблица — транспорты, которые собраны в приложение.
//
// Собирается своя, а не берётся transports.Init() из lyrebird: там
// заодно идут obfs2, obfs3 и scramblesuit, давно снятые с вооружения.
// Новый транспорт добавляется одной строкой здесь.
//
// Почему их четыре, а не один. Сначала был только obfs4 — и на
// мобильных сетях российских операторов он не подключается: DPI научился
// его узнавать. Остальные три отличаются тем, за что их принимает сеть:
//
//	obfs4     — поток без признаков, «случайные байты». Быстрый; там,
//	            где его научились узнавать, не работает вовсе.
//	webtunnel — прикидывается обычным HTTPS к настоящему сайту. Для
//	            сети выглядит как посещение веб-страницы, и различить
//	            это трудно. Первый, что стоит пробовать под DPI.
//	snowflake — идёт не к постоянному мосту, а к добровольцам через
//	            WebRTC, как видеозвонок. Блокировать нечего: адреса
//	            меняются. Мешает разве что мобильный NAT.
//	meek_lite — прячется за большим CDN: снаружи видно обращение к
//	            крупному облаку, а не к тору. Медленный, но живучий.
//
// Плата за это — размер: snowflake тянет pion/webrtc, webtunnel — utls.
// Приложение тяжелеет на несколько мегабайт, и это правильный обмен:
// прокси, который не подключается, не нужен вовсе.
var таблица = map[string]base.Transport{
	"obfs4":     &obfs4.Transport{},
	"webtunnel": webtunnel.Transport,
	"snowflake": &snowflake.Transport{},
	"meek_lite": &meeklite.Transport{},
}

// СрокНабора — сколько ждать TCP-соединения с мостом.
//
// У net.Dial срока нет вовсе, и без этого попытка достучаться до
// заблокированного моста висела до самого конца подключения: сеть
// молча роняет пакеты, а мы молча ждём.
const СрокНабора = 20 * time.Second

// СрокРукопожатия — сколько ждать, пока транспорт договорится с мостом
// после того, как TCP уже открылся.
//
// У самих транспортов срок свой и щедрый — около минуты. Там, где
// соединение глушит DPI, ответа не будет никогда, и эта минута уходит
// впустую на каждый мост подряд. Двадцати секунд хватает любому живому
// мосту, включая медленные.
const СрокРукопожатия = 20 * time.Second

// разборОтказа объясняет отказ по-человечески и говорит, что делать.
//
// Совет разный, и это не вежливость: смена мостов при DPI не помогает,
// а смена транспорта при закрытом порте — не всегда.
func разборОтказа(транспорт string, дошлоДоTCP bool) string {
	if !дошлоДоTCP {
		return "Причина: соединение с мостом не открылось на уровне TCP. " +
			"Адрес или порт недоступны — мост нерабочий, либо сеть режет " +
			"этот порт. Так делают мобильные операторы: у них проходят " +
			"обычно только 80 и 443. Возьмите мост на 443 или другой " +
			"транспорт."
	}
	if транспорт == "obfs4" {
		return "Причина: соединение с мостом открылось, но рукопожатие " +
			"оборвалось. Это признак DPI: сеть пропустила соединение и " +
			"разорвала его, узнав obfs4. Менять мосты тут бесполезно — " +
			"нужен другой транспорт: webtunnel (выглядит как обычный HTTPS) " +
			"или snowflake (постоянного адреса нет вовсе)."
	}
	return "Причина: соединение с мостом открылось, но рукопожатие " +
		"оборвалось. Либо мост нерабочий, либо сеть распознала транспорт " +
		"«" + транспорт + "». Стоит попробовать другой транспорт."
}

// New создаёт Runner. Ничего не поднимает.
func New(opts Options) *Local {
	return &Local{настройки: opts}
}

// Supported перечисляет транспорты, которые умеет поднять эта сборка.
// Порядок устойчивый: список попадает в текст ошибки.
func Supported() []string {
	имена := make([]string, 0, len(таблица))
	for имя := range таблица {
		имена = append(имена, имя)
	}
	sort.Strings(имена)
	return имена
}

// перехватЖурнала переводит стандартный вывод библиотек в наш журнал.
//
// Транспорты из lyrebird — прежде всего snowflake — рассказывают о себе
// через стандартный log: «Rendezvous using Broker at…», «Negotiating via
// HTTP rendezvous…», NAT и прочее. Это самые ценные строки при разборе
// отказа: по ним видно, на каком именно шаге всё встало. Без перехвата
// они уходят в стандартный вывод, которого на телефоне не видит никто.
//
// Перехват глобальный — иначе никак, стандартный логгер в Go один на
// процесс. Ставится он один раз, а приёмник у него сменный: иначе
// вывод библиотек навсегда достался бы журналу того, кто запустился
// первым. Это не украшательство — на этом попался тест: он поднимал
// свой Runner и не получал ни строки, потому что перехват уже был
// занят чужим.
//
// Не отменяется: библиотеки пишут и после остановки транспорта, и
// терять эти строки тоже не хочется.
var (
	перехватЖурнала sync.Once
	приёмникЖурнала atomic.Pointer[func(string)]
)

// вЖурнал превращает поток байтов от log в строки нашего журнала.
type вЖурнал struct{}

func (вЖурнал) Write(данные []byte) (int, error) {
	писать := приёмникЖурнала.Load()
	if писать == nil {
		return len(данные), nil
	}
	// log добавляет перевод строки; свои отметки времени у него тоже
	// есть, но в журнале уже стоят наши, поэтому оставляем как есть —
	// двойная отметка мешает меньше, чем потерянная строка.
	строка := strings.TrimRight(string(данные), "\r\n")
	if строка != "" {
		(*писать)(строка)
	}
	return len(данные), nil
}

func (л *Local) Start(имена []string, stateDir string) ([]Plugin, error) {
	if len(имена) == 0 {
		return nil, nil
	}
	if stateDir == "" {
		return nil, errors.New("транспортам нужен каталог состояния")
	}
	л.мьютекс.Lock()
	if len(л.слушатели) > 0 {
		л.мьютекс.Unlock()
		return nil, errors.New("транспорты уже подняты")
	}
	л.остановлен = false
	л.мьютекс.Unlock()

	if л.настройки.Log != nil {
		приёмникЖурнала.Store(&л.настройки.Log)
		перехватЖурнала.Do(func() {
			log.SetOutput(вЖурнал{})
			log.SetFlags(0)
		})
	}

	var плагины []Plugin
	for _, имя := range имена {
		плагин, err := л.поднять(имя, stateDir)
		if err != nil {
			// Поднялось не всё — не оставляем половину висеть.
			_ = л.Stop()
			return nil, err
		}
		плагины = append(плагины, плагин)
	}
	return плагины, nil
}

// поднять запускает одного слушателя под один транспорт. По слушателю на
// транспорт, а не один общий: у каждого транспорта своя фабрика, и
// разделять их проще, чем угадывать по параметрам, кто пришёл.
func (л *Local) поднять(имя, stateDir string) (Plugin, error) {
	транспорт, известен := таблица[имя]
	if !известен {
		return Plugin{}, fmt.Errorf(
			"транспорт %q не поддерживается; доступны: %s",
			имя, strings.Join(Supported(), ", "))
	}

	фабрика, err := транспорт.ClientFactory(stateDir)
	if err != nil {
		return Plugin{}, fmt.Errorf("транспорт %s не готов: %w", имя, err)
	}

	// Порт нулевой: свободный выберет система, и он же уйдёт в torrc.
	// Фиксировать порт нельзя — на телефоне он может быть занят чем угодно.
	слушатель, err := pt.ListenSocks("tcp", "127.0.0.1:0")
	if err != nil {
		return Plugin{}, fmt.Errorf("транспорт %s не занял порт: %w", имя, err)
	}

	л.мьютекс.Lock()
	л.слушатели = append(л.слушатели, слушатель)
	л.мьютекс.Unlock()

	л.ожидание.Add(1)
	go func() {
		defer л.ожидание.Done()
		л.принимать(имя, слушатель, фабрика)
	}()

	л.записать(fmt.Sprintf("Транспорт %s слушает %s", имя, слушатель.Addr()))
	return Plugin{Transports: []string{имя}, Address: слушатель.Addr().String()}, nil
}

func (л *Local) принимать(имя string, слушатель *pt.SocksListener, фабрика base.ClientFactory) {
	for {
		соединение, err := слушатель.AcceptSocks()
		if err != nil {
			л.мьютекс.Lock()
			остановлен := л.остановлен
			л.мьютекс.Unlock()
			if остановлен {
				return
			}
			var сетевая net.Error
			if errors.As(err, &сетевая) {
				// Временная неурядица — соединение отбросили, слушаем дальше.
				continue
			}
			л.записать(fmt.Sprintf("Транспорт %s перестал принимать соединения: %v", имя, err))
			return
		}

		л.ожидание.Add(1)
		go func() {
			defer л.ожидание.Done()
			л.обслужить(имя, соединение, фабрика)
		}()
	}
}

// обслужить проводит одно соединение через транспорт.
func (л *Local) обслужить(имя string, соединение *pt.SocksConn, фабрика base.ClientFactory) {
	defer func() { _ = соединение.Close() }()

	// Параметры моста tor передаёт в полях аутентификации SOCKS — там же
	// живут cert= и iat-mode=. Разбирает их сам транспорт.
	аргументы, err := фабрика.ParseArgs(&соединение.Req.Args)
	if err != nil {
		л.записать(fmt.Sprintf("Транспорт %s: негодные параметры моста: %v", имя, err))
		_ = соединение.Reject()
		return
	}

	// Наружу идём обычным набором соединения, но не голым net.Dial:
	// подменяем его своим, чтобы знать, дошло ли дело до TCP.
	//
	// Это единственный способ отличить две совершенно разные беды,
	// которые снаружи выглядят одинаково — «tor застрял на 10 %»:
	//
	//   TCP не открылся      — адрес или порт моста недоступны. Так
	//                          ведут себя мобильные операторы, которые
	//                          рубят всё, кроме привычных портов;
	//   TCP открылся, а
	//   рукопожатие упало    — сеть пропустила соединение и оборвала
	//                          его, разобравшись в содержимом. Это DPI,
	//                          и лечится он сменой транспорта, а не
	//                          сменой моста.
	//
	// Без этого различия пользователь мог только гадать, а мы — только
	// советовать «попробуйте другие мосты», что в половине случаев
	// бесполезно.
	var дошлоДоTCP bool
	var сырое net.Conn
	набор := base.DialFunc(func(сеть, адрес string) (net.Conn, error) {
		соед, err := net.DialTimeout(сеть, адрес, СрокНабора)
		if err != nil {
			return nil, err
		}
		дошлоДоTCP = true
		сырое = соед
		// Срок на рукопожатие. Без него отказ выяснялся минуту на
		// каждый мост: у заглушённого DPI соединения ответ не приходит
		// никогда, и чтение висит до собственного срока транспорта.
		// Пользователь всё это время смотрит на «14 %».
		_ = соед.SetDeadline(time.Now().Add(СрокРукопожатия))
		return соед, nil
	})

	удалённое, err := фабрика.Dial("tcp", соединение.Req.Target, набор, аргументы)
	if err != nil {
		л.записать(fmt.Sprintf("Транспорт %s: мост %s не ответил: %v",
			имя, соединение.Req.Target, err))
		л.записать(разборОтказа(имя, дошлоДоTCP))
		_ = соединение.Reject()
		return
	}
	defer func() { _ = удалённое.Close() }()

	// Рукопожатие прошло — срок снимаем. Дальше через это соединение
	// качают файлы и держат долгие сессии, и любой срок оборвал бы их
	// на середине.
	if сырое != nil {
		_ = сырое.SetDeadline(time.Time{})
	}

	if err := соединение.Grant(&net.TCPAddr{IP: net.IPv4zero, Port: 0}); err != nil {
		л.записать(fmt.Sprintf("Транспорт %s: не удалось подтвердить SOCKS: %v", имя, err))
		return
	}

	перекачать(соединение, удалённое)
}

// перекачать гоняет байты в обе стороны и возвращается, когда любая из
// сторон закрылась.
func перекачать(первое, второе net.Conn) {
	готово := make(chan struct{}, 2)
	go func() {
		_, _ = io.Copy(первое, второе)
		готово <- struct{}{}
	}()
	go func() {
		_, _ = io.Copy(второе, первое)
		готово <- struct{}{}
	}()
	<-готово
}

// Stop закрывает слушателей и дожидается, пока разойдутся обработчики.
// Безопасен при повторном вызове и до Start.
func (л *Local) Stop() error {
	л.мьютекс.Lock()
	слушатели := л.слушатели
	л.слушатели = nil
	л.остановлен = true
	л.мьютекс.Unlock()

	var первая error
	for _, слушатель := range слушатели {
		if err := слушатель.Close(); err != nil && первая == nil {
			первая = err
		}
	}
	л.ожидание.Wait()

	if len(слушатели) > 0 {
		л.записать("Транспорты остановлены")
	}
	return первая
}

func (л *Local) записать(строка string) {
	if л.настройки.Log != nil {
		л.настройки.Log(строка)
	}
}
