// Package httpproxy отдаёт наружу HTTP-прокси, а внутрь ходит через
// SOCKS5 тора.
//
// Зачем он нужен, если SOCKS5 уже есть. Многие программы умеют только
// HTTP-прокси, а на iOS дело хуже: системные настройки Wi-Fi знают
// исключительно HTTP-прокси, SOCKS в них нет вовсе, и своих настроек
// прокси у большинства приложений iOS не бывает. Без этого слоя на
// iPhone наш прокси попросту некуда вписать.
//
// Поддерживаются оба способа, которыми пользуются клиенты:
//
//   - CONNECT host:port — для HTTPS и всего остального поверх TLS.
//     Мы открываем поток через SOCKS5 и дальше просто перекачиваем
//     байты в обе стороны, не заглядывая внутрь;
//   - обычный запрос с полным адресом в строке (GET http://host/path) —
//     для незашифрованного HTTP.
//
// Имена узлов мы не разрешаем сами и передаём их в SOCKS5 как есть:
// иначе запрос к DNS ушёл бы мимо тора и выдал, куда идёт пользователь.
package httpproxy

import (
	"context"
	"errors"
	"fmt"
	"io"
	"net"
	"net/http"
	"strings"
	"sync"
	"time"

	"golang.org/x/net/proxy"
)

// СрокСоединения — сколько ждём, пока тор откроет поток к узлу.
// Через мосты первое соединение бывает медленным, поэтому срок щедрый.
const СрокСоединения = 60 * time.Second

// Options — настройки прокси.
type Options struct {
	// Listen — где слушать. Пустое значение означает 127.0.0.1:0,
	// то есть «любой свободный порт на локальном адресе».
	//
	// Слушать что-либо, кроме локального адреса, нельзя: открытый
	// наружу вход в тор стал бы бесплатным прокси для всего интернета,
	// а отвечать за его трафик пришлось бы владельцу выходного узла.
	Listen string
	// Socks — адрес SOCKS5 тора, куда переправлять соединения.
	Socks string
	// Log — куда писать о происходящем. Пусто — молчать.
	Log func(строка string)
}

// Server — сам прокси. Пока не вызван Start, ничего не слушает.
type Server struct {
	настройки Options

	мьютекс   sync.Mutex
	слушатель net.Listener
	сервер    *http.Server
}

// New готовит прокси, но не запускает его.
func New(настройки Options) *Server {
	return &Server{настройки: настройки}
}

// Start поднимает прокси и возвращает управление сразу, как только
// стало известно, что порт занят нами и соединения принимаются.
func (с *Server) Start() error {
	с.мьютекс.Lock()
	defer с.мьютекс.Unlock()

	if с.слушатель != nil {
		return errors.New("http-прокси уже запущен")
	}
	if с.настройки.Socks == "" {
		return errors.New("не указан адрес SOCKS5")
	}

	адрес := с.настройки.Listen
	if адрес == "" {
		адрес = "127.0.0.1:0"
	}
	слушатель, err := net.Listen("tcp", адрес)
	if err != nil {
		return fmt.Errorf("не удалось занять %s: %w", адрес, err)
	}

	сервер := &http.Server{
		Handler: с,
		// Заголовки должны прийти быстро: тянуть их часами незачем,
		// а вот тело запроса и ответ ограничивать по времени нельзя —
		// через прокси качают файлы и держат длинные соединения.
		ReadHeaderTimeout: 30 * time.Second,
	}
	с.слушатель = слушатель
	с.сервер = сервер

	go func() {
		if err := сервер.Serve(слушатель); err != nil &&
			!errors.Is(err, http.ErrServerClosed) {
			с.записать("http-прокси остановлен: " + err.Error())
		}
	}()

	с.записать("http-прокси слушает " + слушатель.Addr().String())
	return nil
}

// Address — адрес, на котором прокси слушает. Пусто, если не запущен.
func (с *Server) Address() string {
	с.мьютекс.Lock()
	defer с.мьютекс.Unlock()

	if с.слушатель == nil {
		return ""
	}
	return с.слушатель.Addr().String()
}

// Stop закрывает прокси. Уже открытые соединения обрываются: ждать,
// пока пользователь докачает файл, тут не надо — он сам нажал
// «отключить».
func (с *Server) Stop() error {
	с.мьютекс.Lock()
	сервер, слушатель := с.сервер, с.слушатель
	с.сервер, с.слушатель = nil, nil
	с.мьютекс.Unlock()

	if сервер == nil {
		return nil
	}
	_ = слушатель.Close()
	return сервер.Close()
}

// ServeHTTP разбирает, чего от нас хотят, и выбирает один из двух
// способов работы.
func (с *Server) ServeHTTP(ответ http.ResponseWriter, запрос *http.Request) {
	if запрос.Method == http.MethodConnect {
		с.туннель(ответ, запрос)
		return
	}
	с.переслать(ответ, запрос)
}

// туннель обслуживает CONNECT: открывает поток через тор и сшивает его
// с соединением клиента.
func (с *Server) туннель(ответ http.ResponseWriter, запрос *http.Request) {
	цель := запрос.Host
	if цель == "" {
		цель = запрос.URL.Host
	}
	if _, _, err := net.SplitHostPort(цель); err != nil {
		// CONNECT без порта — не наш случай, но клиенты попадаются
		// разные; для HTTPS порт по умолчанию известен.
		цель = net.JoinHostPort(цель, "443")
	}

	наружу, err := с.открытьЧерезTor(запрос.Context(), цель)
	if err != nil {
		с.отказ(ответ, цель, err)
		return
	}
	defer func() { _ = наружу.Close() }()

	// Забираем соединение у http-сервера: дальше это уже не HTTP, а
	// просто два потока байтов.
	перехват, годится := ответ.(http.Hijacker)
	if !годится {
		http.Error(ответ, "туннель не поддерживается", http.StatusInternalServerError)
		return
	}
	клиент, буфер, err := перехват.Hijack()
	if err != nil {
		с.записать("не удалось перехватить соединение: " + err.Error())
		return
	}
	defer func() { _ = клиент.Close() }()

	if _, err := клиент.Write([]byte("HTTP/1.1 200 Connection Established\r\n\r\n")); err != nil {
		return
	}
	// Клиент мог прислать начало TLS-приветствия следом за CONNECT —
	// оно уже лежит в буфере сервера, и потерять его нельзя.
	if буфер.Reader.Buffered() > 0 {
		if _, err := io.CopyN(наружу, буфер, int64(буфер.Reader.Buffered())); err != nil {
			return
		}
	}
	перекачать(клиент, наружу)
}

// переслать обслуживает обычный HTTP-запрос с полным адресом в строке.
func (с *Server) переслать(ответ http.ResponseWriter, запрос *http.Request) {
	if !запрос.URL.IsAbs() {
		// Такой запрос пришёл к нам как к обычному сайту, а не как к
		// прокси. Объясняем словами: чаще всего это значит, что адрес
		// вписан не в поле прокси, а в адресную строку.
		http.Error(ответ,
			"Это прокси-сервер, а не сайт. Впишите его адрес в настройки прокси "+
				"(тип HTTP), а не в адресную строку.", http.StatusBadRequest)
		return
	}

	цель := запрос.URL.Host
	if _, _, err := net.SplitHostPort(цель); err != nil {
		цель = net.JoinHostPort(цель, "80")
	}

	наружу, err := с.открытьЧерезTor(запрос.Context(), цель)
	if err != nil {
		с.отказ(ответ, цель, err)
		return
	}
	defer func() { _ = наружу.Close() }()

	// Пишем запрос узлу сами, а не через http.Client: так сохраняется
	// ровно то, что прислал клиент, и не появляется лишних заголовков.
	очищенный := запрос.Clone(запрос.Context())
	убратьПрокси(очищенный.Header)
	if err := очищенный.Write(наружу); err != nil {
		с.записать("не удалось отправить запрос: " + err.Error())
		return
	}

	перехват, годится := ответ.(http.Hijacker)
	if !годится {
		http.Error(ответ, "пересылка не поддерживается", http.StatusInternalServerError)
		return
	}
	клиент, _, err := перехват.Hijack()
	if err != nil {
		с.записать("не удалось перехватить соединение: " + err.Error())
		return
	}
	defer func() { _ = клиент.Close() }()

	// Ответ узла отдаём клиенту как есть, вместе со строкой состояния и
	// заголовками. Разбирать его нам незачем.
	перекачать(клиент, наружу)
}

// открытьЧерезTor открывает поток к узлу через SOCKS5 тора.
//
// Имя узла передаётся в SOCKS5 строкой, а не адресом: разрешать его
// самим нельзя — запрос к DNS ушёл бы мимо тора.
func (с *Server) открытьЧерезTor(ctx context.Context, цель string) (net.Conn, error) {
	посредник, err := proxy.SOCKS5("tcp", с.настройки.Socks, nil, &net.Dialer{
		Timeout: СрокСоединения,
	})
	if err != nil {
		return nil, err
	}
	срок, отмена := context.WithTimeout(ctx, СрокСоединения)
	defer отмена()

	if сДиалом, годится := посредник.(proxy.ContextDialer); годится {
		return сДиалом.DialContext(срок, "tcp", цель)
	}
	return посредник.Dial("tcp", цель)
}

// отказ объясняет клиенту, почему не вышло. Текст виден в браузере,
// поэтому он на русском и без внутренних подробностей.
func (с *Server) отказ(ответ http.ResponseWriter, цель string, err error) {
	с.записать("не удалось открыть " + цель + ": " + err.Error())
	http.Error(ответ,
		"Не удалось открыть "+цель+" через Tor. Проверьте, что подключение "+
			"установлено, и посмотрите журнал.", http.StatusBadGateway)
}

func (с *Server) записать(строка string) {
	if с.настройки.Log != nil {
		с.настройки.Log(строка)
	}
}

// перекачать сшивает два соединения и ждёт, пока оба не закончатся.
func перекачать(один, второй net.Conn) {
	готово := make(chan struct{}, 2)
	копия := func(куда, откуда net.Conn) {
		_, _ = io.Copy(куда, откуда)
		// Закрываем запись на той стороне, куда больше нечего писать:
		// иначе собеседник будет ждать продолжения до самого таймаута.
		if сЗакрытием, годится := куда.(interface{ CloseWrite() error }); годится {
			_ = сЗакрытием.CloseWrite()
		}
		готово <- struct{}{}
	}
	go копия(один, второй)
	go копия(второй, один)
	<-готово
	<-готово
}

// убратьПрокси вычищает заголовки, которые адресованы нам и наружу
// уходить не должны.
func убратьПрокси(заголовки http.Header) {
	for имя := range заголовки {
		if strings.HasPrefix(strings.ToLower(имя), "proxy-") {
			заголовки.Del(имя)
		}
	}
}
