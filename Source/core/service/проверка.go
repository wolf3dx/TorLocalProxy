package service

// Проверка подключения живым запросом.
//
// Зачем она вообще нужна. Раньше служба считала подключение удавшимся,
// как только tor сообщал «Bootstrapped 100%». Это оказалось неправдой:
// сто процентов означают лишь, что tor собрал служебную цепочку и
// получил справочник сети — в том числе из кэша, оставшегося с прошлого
// раза. Наружу при этом может не идти ни байта: мосты отвалились, а tor
// об этом ещё не знает и честно показывает сотню.
//
// Для человека это выглядит так: в окне горит ВКЛЮЧЕНО, а Telegram
// пишет «подключение к прокси» и не подключается никогда. Хуже того,
// перебор типов мостов на таком мнимом успехе останавливается: служба
// запоминает тип как рабочий и больше не пробует остальные.
//
// Поэтому после ста процентов мы делаем то, что сделал бы человек, —
// идём через собственный прокси наружу. Прошло — значит правда работает.

import (
	"context"
	"errors"
	"fmt"
	"time"

	"golang.org/x/net/proxy"
)

// ОшибкаНетТрафика — подключение формально есть, но наружу ничего не
// идёт. Отдельная ошибка, а не просто текст: по ней Connect понимает,
// что надо пробовать следующий тип мостов.
var ОшибкаНетТрафика = errors.New("через прокси не проходит трафик")

// СрокПробы — сколько ждать ответа на один пробный запрос.
//
// Двадцать секунд, а не пять: через три узла Tor да ещё и через мост
// ответ редко приходит быстрее секунды, а на мобильной сети и десять
// не редкость. Короткий срок давал бы ложную тревогу на медленной, но
// работающей связи.
const СрокПробы = 20 * time.Second

// ПериодСторожа — как часто перепроверять связь после подключения.
//
// Полминуты — компромисс. Чаще значит будить радиомодуль телефона
// попусту и жечь батарею; реже — человек успеет решить, что сломалось
// его приложение, а не прокси.
const ПериодСторожа = 30 * time.Second

// ПровальныхПодряд — сколько проверок подряд должны не пройти, прежде
// чем гасить надпись.
//
// Одной мало: цепочка Tor живёт минутами и иногда рвётся сама, а tor
// строит новую за несколько секунд. Дёргать человека на каждую такую
// заминку — значит приучить его не верить индикатору.
const ПровальныхПодряд = 2

// кудаСтучаться — узлы для пробного соединения.
//
// Их несколько, и достаточно одного дошедшего: любой отдельный сайт
// может лежать сам по себе, и объявлять из-за этого прокси сломанным
// нельзя. Имена вперемешку с голым адресом нарочно — имя заодно
// проверяет, что через выходной узел работает и разрешение имён.
var кудаСтучаться = []string{
	"check.torproject.org:443",
	"www.wikipedia.org:443",
	"1.1.1.1:443",
}

// проверитьТрафик пробует дойти наружу через наш же SOCKS5.
//
// Полноценный запрос HTTP не делается нарочно: SOCKS5 отвечает успехом
// только после того, как выходной узел действительно открыл соединение
// с нужным узлом. Значит цепочка построена и данные по ней ходят — а
// это и есть то, что мы хотим знать. Качать при этом чужую страницу
// незачем: лишний трафик и лишняя зависимость от содержимого сайта.
func проверитьТрафик(ctx context.Context, socks string) error {
	if socks == "" {
		return errors.New("адрес прокси неизвестен")
	}
	// proxy.SOCKS5 с nil-forward берёт обычный net.Dialer.
	дозвон, err := proxy.SOCKS5("tcp", socks, nil, proxy.Direct)
	if err != nil {
		return fmt.Errorf("не настроить клиента SOCKS5: %w", err)
	}
	// Приведение к интерфейсу с контекстом: без него нельзя прервать
	// проверку по отмене, и она висела бы весь свой срок уже после
	// нажатия «Отключить».
	сКонтекстом, ок := дозвон.(proxy.ContextDialer)
	if !ок {
		return errors.New("клиент SOCKS5 не умеет работать с контекстом")
	}

	var последняя error
	for _, узел := range кудаСтучаться {
		if err := ctx.Err(); err != nil {
			return err
		}
		сроковый, отмена := context.WithTimeout(ctx, СрокПробы)
		соединение, err := сКонтекстом.DialContext(сроковый, "tcp", узел)
		отмена()
		if err == nil {
			_ = соединение.Close()
			return nil
		}
		последняя = fmt.Errorf("%s: %w", узел, err)
	}
	return fmt.Errorf("%w (%v)", ОшибкаНетТрафика, последняя)
}

// убедитьсяВТрафике — проверка на этапе подключения, с записью в журнал.
//
// Отдельной обёрткой, а не прямо в подключитьГруппу, чтобы человеку в
// журнале было видно обе вещи: что проверка вообще была и сколько она
// заняла. Без этого «тип не подошёл» выглядело бы необъяснимо после
// бодрых ста процентов.
func (s *Service) убедитьсяВТрафике(ctx context.Context, socks string) error {
	проверить := s.настройки.Verify
	if проверить == nil {
		проверить = проверитьТрафик
	}

	s.записать("Проверяю, идёт ли трафик через прокси")
	начало := time.Now()
	err := проверить(ctx, socks)
	заняло := time.Since(начало).Truncate(time.Millisecond)

	if err != nil {
		s.записать(fmt.Sprintf("Трафик не пошёл за %v: %v", заняло, err))
		return err
	}
	s.записать(fmt.Sprintf("Трафик идёт, ответ за %v", заняло))
	return nil
}

// запуститьСторожа заводит повторную проверку связи на время работы.
//
// Одной проверки при подключении мало: мост может отвалиться через час,
// и тогда снова получится «в окне хорошо, а ничего не работает».
// Сторож гасит надпись сам и сам же зажигает обратно, когда связь
// вернулась, — ждать от человека нажатия «Отключить/Подключить» на то,
// что чинится само, неправильно.
//
// Останавливается в свернуть() вместе со всем остальным.
func (s *Service) запуститьСторожа(socks string) {
	ctx, отмена := context.WithCancel(context.Background())

	s.мьютекс.Lock()
	// На всякий случай снимаем прежнего: двух сторожей быть не должно,
	// иначе они будут наперегонки менять состояние.
	if s.сторож != nil {
		s.сторож()
	}
	s.сторож = отмена
	s.мьютекс.Unlock()

	go s.сторожить(ctx, socks, ПериодСторожа)
}

// остановитьСторожа снимает повторную проверку. Безопасно при повторном
// вызове и когда сторожа нет вовсе.
func (s *Service) остановитьСторожа() {
	s.мьютекс.Lock()
	отмена := s.сторож
	s.сторож = nil
	s.мьютекс.Unlock()

	if отмена != nil {
		отмена()
	}
}

// сторожить — сам цикл повторной проверки.
//
// Период передаётся отдельно, а не берётся из ПериодСторожа: тесты
// гоняют тот же цикл с периодом в миллисекунды, иначе одна проверка
// поведения стоила бы минуты ожидания.
func (s *Service) сторожить(ctx context.Context, socks string, период time.Duration) {
	часы := time.NewTicker(период)
	defer часы.Stop()

	проверить := s.настройки.Verify
	if проверить == nil {
		проверить = проверитьТрафик
	}

	подряд := 0
	for {
		select {
		case <-ctx.Done():
			return
		case <-часы.C:
		}

		// Пока идёт переподключение, сторожу делать нечего: он будет
		// мерить недостроенную цепочку и ругаться впустую.
		if s.State() != StateConnected && s.State() != StateFailed {
			continue
		}

		err := проверить(ctx, socks)
		if ctx.Err() != nil {
			return
		}

		if err != nil {
			подряд++
			s.записать(fmt.Sprintf("Проверка связи не прошла (%d из %d): %v",
				подряд, ПровальныхПодряд, err))
			if подряд >= ПровальныхПодряд && s.State() == StateConnected {
				s.записать("Трафик через прокси не идёт — гашу «ВКЛЮЧЕНО». " +
					"Прокси продолжает работать, проверки продолжаются.")
				s.сменитьСостояние(StateFailed)
			}
			continue
		}

		if подряд > 0 {
			s.записать("Связь восстановилась")
		}
		подряд = 0
		if s.State() == StateFailed {
			s.сменитьСостояние(StateConnected)
		}
	}
}
