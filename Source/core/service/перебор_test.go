// Перебор типов мостов. Ради этого свойства всё и затевалось: на живой
// мобильной сети obfs4 оказался заглушён, а webtunnel прошёл, и заранее
// это не выясняется никак. Значит, человек держит в поле все свои
// мосты, а приложение пробует типы по очереди само.

// транспортыПоТипам изображают ptrun.Runner, который отказывает на
// названных транспортах и запоминает порядок попыток.
type транспортыПоТипам struct {
	отказать map[string]bool
	плагины  []torrun.PTPlugin
	попытки  []string
	// передПопыткой зовётся до отказа или успеха — так тест
	// изображает вмешательство человека посреди подключения.
	передПопыткой func(транспорт string)
}

func (т *транспортыПоТипам) Start(имена []string, _ string) ([]torrun.PTPlugin, error) {
	имя := strings.Join(имена, "+")
	т.попытки = append(т.попытки, имя)
	if т.передПопыткой != nil {
		т.передПопыткой(имя)
	}
	if т.отказать[имя] {
		return nil, errors.New("транспорт " + имя + " не поднялся")
	}
	return т.плагины, nil
}

func (т *транспортыПоТипам) Stop() error { return nil }

func мостыДвухТипов() string {
	return "obfs4 10.0.0.1:443 " + отпечаток + " cert=AAAA iat-mode=0\n" +
		"webtunnel [2001:db8::1]:443 " + отпечаток + " url=https://example.org/x"
}

func TestПереборДоходитДоРабочегоТипа(t *testing.T) {
	запуск := &поддельныйЗапуск{конец: torrun.Endpoint{
		ControlAddress: "127.0.0.1:9051", SocksAddress: "127.0.0.1:9050"}}
	клиент := &поддельныйКлиент{шаги: полныйХод()}
	// webtunnel по порядку идёт первым — пусть он и откажет.
	транспорты := &транспортыПоТипам{
		отказать: map[string]bool{"webtunnel": true},
		плагины:  []torrun.PTPlugin{{Transports: []string{"obfs4"}, Address: "127.0.0.1:41000"}},
	}
	s := службаСРаннером(t, запуск, клиент, транспорты)

	наблюдатель := &записнойНаблюдатель{}
	if err := s.Connect(context.Background(), мостыДвухТипов(), наблюдатель); err != nil {
		t.Fatalf("перебор должен был дойти до obfs4, а вернул ошибку: %v", err)
	}

	if len(транспорты.попытки) != 2 {
		t.Fatalf("попыток %d, ожидалось две: %v", len(транспорты.попытки), транспорты.попытки)
	}
	if транспорты.попытки[0] != "webtunnel" || транспорты.попытки[1] != "obfs4" {
		t.Errorf("порядок попыток %v, ожидался webtunnel, затем obfs4", транспорты.попытки)
	}
	if s.State() != StateConnected {
		t.Errorf("состояние %q, ожидалось %q", s.State(), StateConnected)
	}

	// В tor уходят мосты только того типа, который сейчас пробуется:
	// иначе tor сам полез бы во все и перебор был бы бессмыслен.
	if запуск.мосты != 1 {
		t.Errorf("в tor ушло мостов: %d, ожидался один (только obfs4)", запуск.мосты)
	}

	_, _, строки := наблюдатель.снимок()
	журнал := strings.Join(строки, "\n")
	for _, ожидается := range []string{"Попытка 1 из 2", "не подошёл", "Попытка 2 из 2"} {
		if !strings.Contains(журнал, ожидается) {
			t.Errorf("в журнале нет %q:\n%s", ожидается, журнал)
		}
	}
}

func TestУдачныйТипЗапоминаетсяИИдётПервым(t *testing.T) {
	запуск := &поддельныйЗапуск{конец: torrun.Endpoint{
		ControlAddress: "127.0.0.1:9051", SocksAddress: "127.0.0.1:9050"}}
	клиент := &поддельныйКлиент{шаги: полныйХод()}
	транспорты := &транспортыПоТипам{
		отказать: map[string]bool{"webtunnel": true},
		плагины:  []torrun.PTPlugin{{Transports: []string{"obfs4"}, Address: "127.0.0.1:41000"}},
	}
	s := службаСРаннером(t, запуск, клиент, транспорты)

	if err := s.Connect(context.Background(), мостыДвухТипов(), nil); err != nil {
		t.Fatalf("первое подключение: %v", err)
	}
	if s.LastTransport() != "obfs4" {
		t.Fatalf("запомнился тип %q, ожидался obfs4", s.LastTransport())
	}

	// Второй раз перебирать webtunnel незачем: он уже отказал, а на
	// медленных транспортах такой перебор — минуты ожидания.
	_ = s.Disconnect()
	транспорты.попытки = nil
	if err := s.Connect(context.Background(), мостыДвухТипов(), nil); err != nil {
		t.Fatalf("второе подключение: %v", err)
	}
	if len(транспорты.попытки) == 0 || транспорты.попытки[0] != "obfs4" {
		t.Errorf("вторым разом первым пробовался %v, ожидался запомненный obfs4",
			транспорты.попытки)
	}
}

func TestКогдаНеПодошлоНичего(t *testing.T) {
	запуск := &поддельныйЗапуск{конец: torrun.Endpoint{ControlAddress: "127.0.0.1:9051"}}
	клиент := &поддельныйКлиент{шаги: полныйХод()}
	транспорты := &транспортыПоТипам{
		отказать: map[string]bool{"webtunnel": true, "obfs4": true},
	}
	s := службаСРаннером(t, запуск, клиент, транспорты)

	наблюдатель := &записнойНаблюдатель{}
	err := s.Connect(context.Background(), мостыДвухТипов(), наблюдатель)
	if err == nil {
		t.Fatal("ожидалась ошибка: не подошёл ни один тип")
	}
	if len(транспорты.попытки) != 2 {
		t.Errorf("попыток %d, ожидались обе: %v", len(транспорты.попытки), транспорты.попытки)
	}
	if s.State() != StateFailed {
		t.Errorf("состояние %q, ожидалось %q", s.State(), StateFailed)
	}
}

// Нажатие «Отключить» посреди подключения обязано прекращать перебор.
// Иначе человек просит остановиться, а приложение вместо этого начинает
// пробовать следующий тип — и так по всему списку.
func TestПрерываниеНеПродолжаетПеребор(t *testing.T) {
	запуск := &поддельныйЗапуск{конец: torrun.Endpoint{ControlAddress: "127.0.0.1:9051"}}
	клиент := &поддельныйКлиент{шаги: полныйХод()}

	транспорты := &транспортыПоТипам{
		отказать: map[string]bool{"webtunnel": true, "obfs4": true},
	}
	s := службаСРаннером(t, запуск, клиент, транспорты)
	транспорты.передПопыткой = func(транспорт string) {
		if транспорт == "webtunnel" {
			// Человек нажал «Отключить», пока шла первая попытка.
			_ = s.Disconnect()
		}
	}

	err := s.Connect(context.Background(), мостыДвухТипов(), nil)
	if err == nil {
		t.Fatal("прерванное подключение не должно возвращаться успехом")
	}
	if len(транспорты.попытки) != 1 {
		t.Errorf("после прерывания попыток %d, ожидалась одна: %v",
			len(транспорты.попытки), транспорты.попытки)
	}
}

// службаСРаннером — как службаСТранспортами, но с любым Runner, а не
// только с поддельныеТранспорты.
func службаСРаннером(t *testing.T, запуск *поддельныйЗапуск, клиент *поддельныйКлиент,
	транспорты *транспортыПоТипам) *Service {
	t.Helper()
	s, err := New(Options{
		StateDir:   t.TempDir(),
		Runtime:    запуск,
		Transports: транспорты,
		Dial: func(context.Context, string, control.Options) (control.Client, error) {
			return клиент, nil
		},
	})
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	return s
}
