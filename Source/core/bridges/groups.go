// Работа с несколькими типами мостов сразу.
//
// Раньше приложение считало, что мосты в поле одного типа: разобрали и
// отдали tor целиком. Оказалось, так нельзя. На мобильных сетях
// операторов obfs4 глушат по содержимому, webtunnel проходит, а
// snowflake зависит от того, пропускают ли WebRTC. Заранее не угадать,
// поэтому человек держит в поле все свои мосты, а приложение пробует
// типы по очереди, пока какой-нибудь не подключится.
//
// Отсюда три задачи, которые решает этот файл: разложить мосты по
// типам, назвать порядок перебора и убрать из текста мосты одного типа,
// не тронув остальные.
package bridges

import (
	"sort"
	"strconv"
	"strings"
)

// БезТранспорта — метка для обычных мостов, у которых транспорта нет
// вовсе. Пустая строка в роли ключа читается плохо, а в интерфейсе её
// пришлось бы всё равно как-то называть.
const БезТранспорта = "vanilla"

// Group — мосты одного типа.
type Group struct {
	// Transport — имя транспорта или БезТранспорта.
	Transport string
	// Bridges — мосты этого типа в исходном порядке.
	Bridges []Bridge
}

// предпочтение задаёт порядок перебора типов.
//
// Меньше число — раньше пробуем. Порядок не произвольный, он выведен из
// того, как эти транспорты ведут себя под цензурой и сколько времени
// тратят на отказ:
//
//	webtunnel — проходит там, где остальное глушат, и отказывает
//	            быстро. Проверено на мобильной сети: tor дошёл до 100 %,
//	            когда прямой путь был закрыт;
//	obfs4     — самый быстрый, когда работает. Ставится вторым, потому
//	            что под DPI он мёртв, а выясняется это не мгновенно;
//	snowflake — постоянного адреса нет, блокировать нечего, но нужен
//	            WebRTC, и переговоры идут минуты;
//	meek_lite — живучий и самый медленный: последняя надежда.
//
// Обычные мосты без транспорта идут в самом конце: если сеть настолько
// свободна, что они работают, человек и не станет возиться с типами.
var предпочтение = map[string]int{
	"webtunnel":   1,
	"obfs4":       2,
	"snowflake":   3,
	"meek_lite":   4,
	"meek":        5,
	БезТранспорта: 9,
}

// GroupByTransport раскладывает мосты по типам и возвращает группы в
// порядке перебора.
//
// Первым можно поставить любой тип через сначала — так приложение
// вспоминает, чем подключилось в прошлый раз, и не тратит время на
// перебор заново. Пустое значение или незнакомый тип ничего не меняют.
func GroupByTransport(bridges []Bridge, сначала string) []Group {
	по := make(map[string][]Bridge)
	for _, мост := range bridges {
		имя := мост.Transport
		if имя == "" {
			имя = БезТранспорта
		}
		по[имя] = append(по[имя], мост)
	}

	группы := make([]Group, 0, len(по))
	for имя, список := range по {
		группы = append(группы, Group{Transport: имя, Bridges: список})
	}

	sort.SliceStable(группы, func(i, j int) bool {
		// Прошлый удачный тип — вперёд всех.
		if группы[i].Transport == сначала {
			return true
		}
		if группы[j].Transport == сначала {
			return false
		}
		вес := func(имя string) int {
			if в, есть := предпочтение[имя]; есть {
				return в
			}
			// Незнакомый транспорт — после известных, но до обычных
			// мостов: раз человек его вписал, он на что-то надеется.
			return 8
		}
		левый, правый := вес(группы[i].Transport), вес(группы[j].Transport)
		if левый != правый {
			return левый < правый
		}
		return группы[i].Transport < группы[j].Transport
	})
	return группы
}

// Counts считает мосты по типам — для подписи в интерфейсе.
// Порядок тот же, что у перебора.
func Counts(bridges []Bridge) []string {
	var подписи []string
	for _, группа := range GroupByTransport(bridges, "") {
		подписи = append(подписи,
			группа.Transport+": "+strconv.Itoa(len(группа.Bridges)))
	}
	return подписи
}

// RemoveTransport убирает из текста мосты одного типа, оставляя всё
// прочее как было.
//
// Работает по строкам исходного текста, а не по разобранным мостам: в
// поле нередко лежит письмо целиком, с приветствием и подписью, и
// терять это при чистке одного типа нельзя. Строка удаляется только
// если она и правда мост, и правда того типа.
func RemoveTransport(text, transport string) string {
	if transport == "" {
		return text
	}
	искомый := strings.ToLower(transport)

	строки := strings.Split(text, "\n")
	оставшиеся := make([]string, 0, len(строки))
	for _, строка := range строки {
		мост, err := ParseLine(строка)
		if err == nil {
			имя := мост.Transport
			if имя == "" {
				имя = БезТранспорта
			}
			if strings.EqualFold(имя, искомый) {
				continue
			}
		}
		оставшиеся = append(оставшиеся, строка)
	}

	итог := strings.Join(оставшиеся, "\n")
	// Пустые строки на концах после чистки только мешают: поле должно
	// выглядеть так, будто удалённых строк там и не было.
	return strings.TrimSpace(итог)
}
