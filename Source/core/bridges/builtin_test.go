package bridges_test

import (
	"testing"

	"gitlab.com/vkandreevich/torlocalproxy/core/bridges"
)

// Встроенные мосты — то, что приложение предлагает нажатием кнопки,
// когда своих мостов у человека нет. Здесь проверяется главное: они
// разбираются нашим же разборщиком и не содержат ничего, чего сборка
// не умеет поднять. Иначе кнопка выдавала бы отказ вместо помощи.

func TestВстроенныеМостыРазбираются(t *testing.T) {
	годные, беды := bridges.Parse(bridges.Builtin())
	if len(беды) != 0 {
		t.Errorf("во встроенных мостах есть строки с бедами: %v", беды)
	}
	if len(годные) < 2 {
		t.Fatalf("встроенных мостов разобрано %d, ожидалось хотя бы два", len(годные))
	}
}

func TestВстроенныйSnowflakeИдётПервым(t *testing.T) {
	годные, _ := bridges.Parse(bridges.Builtin())
	if len(годные) == 0 {
		t.Fatal("встроенных мостов нет вовсе")
	}
	// Порядок не косметика: snowflake единственный, у кого нет
	// постоянного адреса, и там, где узнают obfs4, он остаётся
	// последней рабочей возможностью. tor пробует мосты по порядку.
	if годные[0].Transport != "snowflake" {
		t.Errorf("первым идёт %q, а должен snowflake", годные[0].Transport)
	}
}

// Транспорты встроенных мостов должны быть в списке известных: иначе
// разбор отвергнет строку раньше, чем дело дойдёт до подключения.
func TestТранспортыВстроенныхИзвестны(t *testing.T) {
	годные, _ := bridges.Parse(bridges.Builtin())
	for _, транспорт := range bridges.Transports(годные) {
		if !bridges.KnownTransports[транспорт] {
			t.Errorf("транспорт %q встроенного моста не значится известным", транспорт)
		}
	}
}
